#!/usr/bin/env node
// Which parked-island modules the `syzygy` CLI loads at runtime (syzygy-bpyt.8.19). Evidence tool, not a check and not authority.
//
//   (in the tree) npm ci && npx tsc -b apps/syzygy apps/three-surface-poc packages/polaris-dossier
//   node scripts/measure_cli_island_loads.mjs <tree> --out <file.json>
//
// It loads, in this process, every module the CLI entry (`apps/syzygy/dist/main.js`) imports: its one static workspace import and
// the targets of its dynamic imports, resolved from the entry's own directory, without running the entry (which would start a
// daemon). A load hook records every module URL Node loads. It reports the loaded modules under `packages/` and `apps/`, and which
// of them are the compiled form of a module in the island list of `packages/polaris-generation-core/src/island-boundary.test.ts`,
// read from that file, or of `packages/polaris-generation-consent/src/consent-ports.ts`. It reads the tree only and writes only `--out`.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import { createRequire, registerHooks } from 'node:module';
import * as path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT_REL = 'scripts/measure_cli_island_loads.mjs';
const ENTRY = 'apps/syzygy/dist/main.js';
const BOUNDARY_TEST = 'packages/polaris-generation-core/src/island-boundary.test.ts';
const CONSENT_PORTS = 'packages/polaris-generation-consent/src/consent-ports.ts';
const argv = process.argv.slice(2);
const tree = argv[0] === undefined || argv[0].startsWith('--') ? undefined : fs.realpathSync(path.resolve(argv[0]));
const out = argv.includes('--out') ? argv[argv.indexOf('--out') + 1] : undefined;
if (tree === undefined || out === undefined) {
  process.stderr.write('usage: node scripts/measure_cli_island_loads.mjs <tree> --out <file.json>\n');
  process.exit(2);
}
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const git = (...args) => execFileSync('git', ['-C', tree, ...args], { encoding: 'utf8' }).trim();

const loaded = new Set();
registerHooks({ load(url, context, nextLoad) { loaded.add(url); return nextLoad(url, context); } });

const entrySource = fs.readFileSync(path.join(tree, 'apps/syzygy/src/main.ts'), 'utf8');
const specifiers = [...new Set([...entrySource.matchAll(/(?:from|import\()\s*'(@syzygy\/[^']+)'/gu)].map(m => m[1]))].sort();
const require = createRequire(path.join(tree, ENTRY));
for (const specifier of specifiers) await import(pathToFileURL(fs.realpathSync(require.resolve(specifier))).href);

const island = [...fs.readFileSync(path.join(tree, BOUNDARY_TEST), 'utf8').matchAll(/^ {2}'((?:apps|packages)\/[^']+\.ts)',$/gmu)].map(m => m[1]);
const compiled = source => source.replace(/\/src\//u, '/dist/').replace(/\.ts$/u, '.js');
const workspace = [...loaded].filter(url => url.startsWith('file:')).map(url => fs.realpathSync(fileURLToPath(url)))
  .filter(file => file.startsWith(`${tree}${path.sep}`)).map(file => path.relative(tree, file).split(path.sep).join('/'))
  .filter(file => /^(?:apps|packages)\//u.test(file) && !file.includes('/node_modules/')).sort();
const loadedSet = new Set(workspace);
const document = {
  schema: 'cli-island-loads/1',
  bead: 'syzygy-bpyt.8.19',
  text: 'Evidence record, not authority: every workspace module the syzygy CLI entry loads at runtime through its imports, and which of them are parked-island modules. Generated by the script named here; do not edit.',
  script: { path: SCRIPT_REL, sha256: sha256(fs.readFileSync(fileURLToPath(import.meta.url))) },
  measuredOn: { commit: git('rev-parse', 'HEAD'), clean: git('status', '--porcelain', '--untracked-files=no') === '', node: process.version },
  entry: ENTRY,
  specifiers,
  islandListed: island.length,
  islandLoaded: island.filter(source => loadedSet.has(compiled(source))),
  consentPortsLoaded: loadedSet.has(compiled(CONSENT_PORTS)),
  workspaceModulesLoaded: workspace.length,
  workspaceModules: workspace,
};
fs.writeFileSync(out, `${JSON.stringify(document, null, 1)}\n`);
process.stderr.write(`${specifiers.length} specifiers, ${workspace.length} workspace modules loaded, island ${document.islandLoaded.length} of ${island.length}, consent-ports ${document.consentPortsLoaded}\n`);
process.exit(0);
