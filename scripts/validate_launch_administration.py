        """`expect` is a substring of a required error, or None to require a
        clean run. Every fixture mutates the base and asserts the check
        fires — a check that cannot fail is not a check."""
        n_cases[0] += 1
        if git and not git_on:
            n_git_skipped[0] += 1
            print(f"  SKIP  {name} (needs a git repository)")
            return
        rec = _base_record(git)
