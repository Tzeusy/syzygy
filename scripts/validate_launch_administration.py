# instrument readers
# ==========================================================================
def param_block_bytes(instrument_text: bytes):
    """§8's bytes: from the '## 8.' heading to the next '## ' heading."""
    txt = instrument_text.decode("utf-8", errors="replace")
    m = re.search(r"^## 8\..*$", txt, re.M)
    if not m:
        return None
    rest = txt[m.start():]
    nxt = re.search(r"^## (?!8\.)", rest[1:], re.M)
    return (rest if not nxt else rest[: nxt.start() + 1]).encode("utf-8")


def _norm_ws(s):
    return re.sub(r"\s+", " ", s).strip()


def instrument_version(instrument_text: bytes):
    m = re.search(r"^effective_version:\s*(v[0-9]+\.[0-9]+)",
                  instrument_text.decode("utf-8", errors="replace"), re.M)
    return m.group(1) if m else None


def launch_target_forms(pb_text):
    m = re.search(r"LAUNCH_TARGET:\s*>\n((?:[ \t]+\S[^\n]*\n)+)", pb_text)
    lt = _norm_ws(m.group(1)) if m else _norm_ws(pb_text)
    return (lt.rstrip("."), lt.split(". ")[0].rstrip("."))


def _yaml_list(pb_text, key):
    m = re.search(re.escape(key) + r":\s*\[([^\]]*)\]", pb_text)
    if not m:
        return None
    return [x.strip() for x in m.group(1).split(",") if x.strip()]


def e4_cases(pb_text):
    """The `E4_CASES` list, each case's quoted text, in the block's order.

    This is the one place the validator reads the instrument's own prose,
    and it is bounded and fail-closed by construction: it starts at the
    `E4_CASES` marker and takes numbered, double-quoted items only while
    their numbers run consecutively from 1, so the walk terminates at the
    first thing that is not the next case rather than wandering into the
    rest of §8. It returns None when it finds no case at all, and LA-10
    treats that as an error — never as "no cases to check". Reading the
    instrument, whose digest the record binds, is categorically different
    from parsing a generated report as authority: the bytes are pinned
    before the read, and a mismatch in count or text is an error either way.
    """
    m = re.search(r"`E4_CASES`", pb_text)
    if not m:
        return None
    out, expect = [], 1
    for item in re.finditer(r"^(\d+)\.[ \t]+\"(.*?)\"",
                            pb_text[m.start():], re.S | re.M):
        if int(item.group(1)) != expect:
            break
        out.append(_norm_ws(item.group(2)))
        expect += 1
    return out or None


