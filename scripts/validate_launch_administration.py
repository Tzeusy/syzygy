def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("record", nargs="?")
    ap.add_argument("--schema", default=None)
    ap.add_argument("--prior", default=None)
    ap.add_argument("--trend-row", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args(argv)

    if args.selftest:
        return _selftest()
    if not args.record:
        ap.error("a record path is required (or --selftest)")

    errors, notes, computed = validate(args.record, args.schema, args.prior)
    for n in notes:
        print(f"note: {n}")
    if computed:
        print(f"Computed gate verdict: {computed['verdict']}")
        for name, ok, why in computed["conjuncts"]:
            print(f"  [{'ok ' if ok else 'NO '}] {name} — {why}")
        print(f"  F2 limb: branch={computed['branch']}, "
              f"deferrals={computed['deferred']}")
        if args.trend_row:
            rec = json.loads(Path(args.record).read_text())
            print("\nTrend row (§6):")
            print(trend_row(rec, computed))
    if errors:
        print(f"\n{len(errors)} validation error(s):")
        for e in errors:
            print(f"  {e}")
        return 1
    print("\nrecord valid — the verdict above is computed from the rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
