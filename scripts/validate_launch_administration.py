#!/usr/bin/env python3
"""Validate a **structured** launch-gate administration record and compute
its verdict and trend row.

Scope, stated so nobody mistakes it: this tool validates the record and
computes its derived figures. Readiness semantics are owned by
`launch-gate-pre-specifications.md` (§4); where this tool applies the §4
formula it is checking the record against the instrument, never deciding
readiness independently of it. A record this tool passes can still support
nothing if the instrument's non-mechanical requirements (fresh context,
family disclosure, a genuine falsification attempt) were not honored —
those live in the record's own fields and the reader's judgment.

**Why this tool exists.** Its predecessor, `launch_gate_results.py`, parsed
a human Markdown report as the machine source of a launch decision. Thirteen
consecutive administrations of that instrument returned `REVISE`, and the
findings converged on one question the Markdown could not answer stably:
*is this line the record's own claim, or a quotation of one?* v2.0 removes
the question rather than answering it again. The canonical record is JSON;
the Markdown is generated by `render_launch_administration.py` and is never
parsed back. There is no Markdown or HTML visibility classifier anywhere in
this file's correctness path.

Checks (each with at least one `--selftest` mutation fixture):

  LA-1  schema conformance against the committed JSON Schema — types, the
        closed verdict vocabulary, required fields, and `additionalProperties:
        false` everywhere, so an unknown key is an error rather than a
        silently ignored one. A `final_verdict` key is rejected here: the
        verdict is computed, and a record that cannot claim one cannot be
        believed about one
  LA-2  identity — the named commit exists; the instrument is committed at
        it; the record's instrument sha256 matches those bytes; the
        parameter-block sha256 matches §8 of those bytes; the declared
        instrument version matches the committed `effective_version`
  LA-3  binding — the record's launch target equals (whitespace-normalized)
        the parameter block's `LAUNCH_TARGET` or its first sentence, and the
        required/deferred wave lists equal the parameter block's
  LA-4  roster — exactly the full question set is answered, once each:
        A1–A6, B1–B5, C1–C7, D1–D4, E1 with its five sub-rows, E2–E6,
        F1–F6. A missing row is an error, never a pass; an extra row is an
        error too, so an invented question cannot enter the computed columns
  LA-5  verdict/scope agreement — `launch_scope: deferred-wave-only` is
        lawful with the scoped verdict and with no other, and the scoped
        verdict only in A–D. The two fields are authored independently and
        cross-checked, so one typo cannot launder a defect out of scope
  LA-6  evidence discipline — `Met` requires at least one evidence entry;
        either `Not met` form requires a counterexample; `Unknown` requires
        both a reason and what would settle it; fields that do not belong to
        the verdict must be null; and every evidence entry is anchored to
        the record's own `repository_commit`
  LA-7  E1 rolls up — `E1` is `Met` only when all five sub-rows are `Met`
  LA-8  scoped rows are disclosed — any scoped row requires a
        `deferred_wave_findings` entry naming that question, and a finding
        that meets any of §4's five blocking conditions cannot support a
        scoped verdict
  LA-9  E3's credibility protocol — `Met` requires the concept enumeration
        and a trace row per concept; a non-empty reopen list forbids `E3 |
        Met` and forbids any READY verdict (§3's self-declared sharpest
        single gate)
  LA-10 E4's fixed cases — one result per `E4_CASES` case, indices exactly
        1..n, each `case_text` equal to the instrument's own case text, so a
        paraphrased case cannot carry a verdict; reviewer/authority
        disagreement forbids `E4 | Met`; and silence over a case the launch
        target needs routed must be recorded in the operationalization notes
  LA-11 deferrals are cited, not asserted — each names a repository path
        that exists at the named commit and is a file, or an `SDR-n` that
        exists in the decisions home; `P-n` (the queue of decisions *not*
        made), `D-n` (a delta item) and `B-n` (review-finding numbering)
        grant nothing; and no deferral may be claimed against a conjunct §4
        calls never deferrable
  LA-12 the §4 formula, computed — both pass branches run the full conjunct
        battery: every E row `Met`, no plain `Not met` in launch-scope A–D,
        F1 `Met`-or-`Unknown`, F3 `Met`, F4 `Met`. Plain `READY FOR`
        additionally requires F2 `Met` and zero deferrals;
        `READY-WITH-DEFERRALS` substitutes exactly the F2 limb with an
        owner-cited deferral and requires a nonzero deferral count
  LA-13 administration integrity — a `formal` administration must be
        `full`, must be fresh-context, and a `delta` record can never
        support a gate decision (§2)
  LA-14 G1 — present, answered, and never a verdict row. The roster (LA-4)
        already refuses a `G1` row; this check refuses a placeholder answer,
        because a G1 section that says "none" is the absence LA-4 would have
        caught wearing the shape of a presence
  LA-15 trend anchoring — a declared prior record must exist, its commit
        must be an ancestor of this record's commit, and its date must not
        follow this one; a `--prior` file must be the record `prior_record`
        names
  LA-16 the pilot-recurrence check (§8 `PILOT_RECURRENCE_CHECK`) is
        performed and its method recorded, on any formal administration
        that opens the trend log

Every free-text field this tool relies on is checked against a placeholder
lexicon: a value whose tokens are all placeholders ("none", "n/a", "tbd")
asserts emptiness, and asserting emptiness is not answering. Presence tests
elsewhere are content-blind by design — the truthfulness of an evidence
quote stays with the reader.

Usage:
  python3 scripts/validate_launch_administration.py <record.json>
      [--schema launch-gate-administration.schema.json]
      [--prior <record.json>] [--trend-row]
  python3 scripts/validate_launch_administration.py --selftest
"""

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_SCHEMA = REPO / "launch-gate-administration.schema.json"
DECISIONS_HOME = ".syzygy/governance/decisions"

# --------------------------------------------------------------------------
# The question roster. Order is presentation order; membership is the check.
# --------------------------------------------------------------------------
ROSTER = (
    [f"A{i}" for i in range(1, 7)]
    + [f"B{i}" for i in range(1, 6)]
    + [f"C{i}" for i in range(1, 8)]
    + [f"D{i}" for i in range(1, 5)]
    + ["E1-form", "E1-home", "E1-granularity", "E1-acceptance-authority",
       "E1-change-process", "E1"]
    + [f"E{i}" for i in range(2, 7)]
    + [f"F{i}" for i in range(1, 7)]
)
ROSTER_SET = frozenset(ROSTER)
E1_SUBROWS = ("E1-form", "E1-home", "E1-granularity",
              "E1-acceptance-authority", "E1-change-process")
E_ROWS = tuple(q for q in ROSTER if q.startswith("E"))
AD_ROWS = tuple(q for q in ROSTER if q[0] in "ABCD")

MET = "Met"
NOT_MET = "Not met"
SCOPED = "Not met (out of launch scope)"
UNKNOWN = "Unknown"

# §4: the conjuncts that carry their own rationale for blocking are never
# deferrable. Only F2 has a deferral limb.
NEVER_DEFERRABLE = frozenset(E_ROWS) | frozenset(AD_ROWS) | {"F1", "F3", "F4"}

# RD35-05's lexicon, carried forward: a value built only of these tokens
# asserts emptiness rather than answering.
_PLACEHOLDER_TOKENS = frozenset((
    "none", "no", "nothing", "nil", "n/a", "na", "tbd", "tba", "todo",
    "unknown", "unspecified", "pending", "-", "--", "—", "(none)", "()",
    "empty", "not", "applicable", "yet", "identified", "found", "known",
))


def _is_placeholder(value: str) -> bool:
    """True when every token falls inside the placeholder lexicon."""
    toks = [t.strip("()[[]].,;:\"'*_`") for t in str(value).lower().split()]
    toks = [t for t in toks if t]
    return not toks or all(t in _PLACEHOLDER_TOKENS for t in toks)


# ==========================================================================
# A deliberately small JSON Schema subset interpreter.
#
# The alternative — re-stating the schema's rules in Python beside the
# committed schema — is the defect RD45-06 named: expectations derived from
# the thing under test. Here the committed schema IS the rule and this code
# only interprets it. The safety property that makes that honest is
# `_audit_schema`: any keyword this interpreter does not implement is a hard
# error when it appears in the schema, so the schema can never quietly rely
# on a keyword that is being ignored.
# ==========================================================================
_SUPPORTED_KEYWORDS = frozenset((
    "$schema", "$id", "title", "description",          # annotations
    "type", "enum", "const", "pattern", "minLength",
    "properties", "required", "additionalProperties",
    "items", "minItems", "uniqueItems",
    "oneOf", "$ref", "$defs",
))
_SCHEMA_VALUED = frozenset(("items",))
_SCHEMA_MAP_VALUED = frozenset(("properties", "$defs"))
_SCHEMA_LIST_VALUED = frozenset(("oneOf",))

_TYPES = {
    "object": lambda v: isinstance(v, dict),
    "array": lambda v: isinstance(v, list),
    "string": lambda v: isinstance(v, str),
    "boolean": lambda v: isinstance(v, bool),
    "null": lambda v: v is None,
    "integer": lambda v: isinstance(v, int) and not isinstance(v, bool),
    "number": lambda v: isinstance(v, (int, float)) and not isinstance(v, bool),
}


def _audit_schema(node, path, out):
    """Reject any keyword the interpreter does not implement."""
    if not isinstance(node, dict):
        out.append(f"{path}: schema node is not an object")
        return
    for k, v in node.items():
        here = f"{path}/{k}"
        if k not in _SUPPORTED_KEYWORDS:
            out.append(f"{here}: unsupported schema keyword {k!r} — this "
                       "validator implements a documented subset, and an "
                       "unimplemented keyword would be silently ignored")
            continue
        if k == "additionalProperties" and v is not False:
            out.append(f"{here}: only `additionalProperties: false` is "
                       "implemented")
        elif k in _SCHEMA_MAP_VALUED:
            if not isinstance(v, dict):
                out.append(f"{here}: expected an object of schemas")
                continue
            for name, sub in v.items():
                _audit_schema(sub, f"{here}/{name}", out)
        elif k in _SCHEMA_VALUED:
            _audit_schema(v, here, out)
        elif k in _SCHEMA_LIST_VALUED:
            if not isinstance(v, list):
                out.append(f"{here}: expected a list of schemas")
                continue
            for i, sub in enumerate(v):
                _audit_schema(sub, f"{here}/{i}", out)


def _resolve(ref, root):
    if not ref.startswith("#/"):
        raise ValueError(f"only local refs are implemented, got {ref!r}")
    node = root
    for part in ref[2:].split("/"):
        node = node[part]
    return node


def _instance_errors(inst, sch, root, path, out):
    """Validate `inst` against `sch`. Appends human-readable errors."""
    if "$ref" in sch:
        _instance_errors(inst, _resolve(sch["$ref"], root), root, path, out)
        return

    if "oneOf" in sch:
        hits = 0
        for sub in sch["oneOf"]:
            probe = []
            _instance_errors(inst, sub, root, path, probe)
            if not probe:
                hits += 1
        if hits != 1:
            out.append(f"{path}: matches {hits} of the oneOf branches, "
                       "exactly one is required")
            return

    if "const" in sch and inst != sch["const"]:
        out.append(f"{path}: expected the constant {sch['const']!r}, "
                   f"found {inst!r}")
        return

    if "enum" in sch and inst not in sch["enum"]:
        out.append(f"{path}: {inst!r} is outside the closed set "
                   f"{sch['enum']!r}")
        return

    if "type" in sch:
        t = sch["type"]
        if not _TYPES[t](inst):
            out.append(f"{path}: expected {t}, found "
                       f"{type(inst).__name__}")
            return

    if isinstance(inst, str):
        if "minLength" in sch and len(inst) < sch["minLength"]:
            out.append(f"{path}: shorter than the required "
                       f"{sch['minLength']} character(s)")
        if "pattern" in sch and not re.search(sch["pattern"], inst):
            out.append(f"{path}: {inst!r} does not match "
                       f"/{sch['pattern']}/")

    if isinstance(inst, list):
        if "minItems" in sch and len(inst) < sch["minItems"]:
            out.append(f"{path}: {len(inst)} item(s), at least "
                       f"{sch['minItems']} required")
        if sch.get("uniqueItems") and len(inst) != len(
                {json.dumps(x, sort_keys=True) for x in inst}):
            out.append(f"{path}: items are not unique")
        if "items" in sch:
            for i, el in enumerate(inst):
                _instance_errors(el, sch["items"], root, f"{path}[{i}]", out)

    if isinstance(inst, dict):
        for req in sch.get("required", []):
            if req not in inst:
                out.append(f"{path}: required field {req!r} is missing — "
                           "an absent field is never an implicit answer")
        props = sch.get("properties", {})
        if sch.get("additionalProperties") is False:
            for k in inst:
                if k not in props:
                    extra = (" — the verdict is computed, never claimed"
                             if k == "final_verdict" else "")
                    out.append(f"{path}: unknown field {k!r}{extra}")
        for k, sub in props.items():
            if k in inst:
                _instance_errors(inst[k], sub, root, f"{path}/{k}", out)


# ==========================================================================
# git helpers (all read-only)
# ==========================================================================
def _git_show(commit, path):
    try:
        out = subprocess.run(["git", "-C", str(REPO), "show",
                              f"{commit}:{path}"], capture_output=True)
        return out.stdout if out.returncode == 0 else None
    except OSError:
        return None


def _commit_exists(sha):
    try:
        return subprocess.run(
            ["git", "-C", str(REPO), "cat-file", "-e", f"{sha}^{{commit}}"],
            capture_output=True).returncode == 0
    except OSError:
        return False


def _is_ancestor(a, b):
    try:
        return subprocess.run(
            ["git", "-C", str(REPO), "merge-base", "--is-ancestor", a, b],
            capture_output=True).returncode == 0
    except OSError:
        return False


def _path_kind(commit, path):
    """'blob', 'tree', or None, at the named commit."""
    try:
        out = subprocess.run(
            ["git", "-C", str(REPO), "cat-file", "-t", f"{commit}:{path}"],
            capture_output=True, text=True)
        return out.stdout.strip() if out.returncode == 0 else None
    except OSError:
        return None


def _sdr_exists(ident, commit):
    """An SDR-n citation must name a decision present in the decisions home
    at the named commit — matched at identifier boundaries, and scoped to
    MADE decisions: a mention in the pending queue grants nothing."""
    pat = r"(^|[^-A-Za-z0-9])" + re.escape(ident) + r"($|[^0-9a-z(])"
    try:
        return subprocess.run(
            ["git", "-C", str(REPO), "grep", "-qE", pat, commit, "--",
             DECISIONS_HOME,
             f":(exclude){DECISIONS_HOME}/PENDING-OWNER-DECISIONS.md"],
            capture_output=True).returncode == 0
    except OSError:
        return False


def _git_available():
    try:
        return subprocess.run(["git", "-C", str(REPO), "rev-parse",
                               "--git-dir"], capture_output=True).returncode == 0
    except OSError:
        return False


