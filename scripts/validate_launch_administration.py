    _expect_verdict("a Not met E row computes NOT READY",
                    lambda r: r["question_results"][ROSTER.index("E5")].update(
                        verdict=NOT_MET, counterexample="x"), "NOT READY")
    _expect_verdict("an Unknown F1 does not block",
                    lambda r: r["question_results"][ROSTER.index("F1")].update(
                        verdict=UNKNOWN, evidence=[],
                        unknown_reason="no trend yet",
                        unknown_settlement="a second administration"),
                    "READY FOR")
    _expect_verdict("a Not met F1 blocks",
                    lambda r: r["question_results"][ROSTER.index("F1")].update(
                        verdict=NOT_MET, counterexample="x"), "NOT READY")
    _expect_verdict("a Not met F3 blocks",
                    lambda r: r["question_results"][ROSTER.index("F3")].update(
                        verdict=NOT_MET, counterexample="x"), "NOT READY")
    _expect_verdict("a Not met F4 blocks",
                    lambda r: r["question_results"][ROSTER.index("F4")].update(
                        verdict=NOT_MET, counterexample="x"), "NOT READY")
    _expect_verdict("a Not met F2 with no deferral blocks",
                    lambda r: r["question_results"][ROSTER.index("F2")].update(
                        verdict=NOT_MET, counterexample="x"), "NOT READY")
    _expect_verdict(
        "a Not met F2 with an owner-cited deferral is READY-WITH-DEFERRALS",
        lambda r: (r["question_results"][ROSTER.index("F2")].update(
            verdict=NOT_MET, counterexample="x"), _defer(r)),
        "READY-WITH-DEFERRALS")
    _expect_verdict(
        "an Unknown F2 is deferrable on the same terms",
        lambda r: (r["question_results"][ROSTER.index("F2")].update(
            verdict=UNKNOWN, evidence=[], unknown_reason="no trend",
            unknown_settlement="two more administrations"), _defer(r)),
        "READY-WITH-DEFERRALS")
    _expect_verdict("a non-empty reopen list blocks every pass branch",
                    lambda r: r["e3"]["reopen_items"].append(
                        {"item": "x", "why": "y"}), "NOT READY")
    case("LA-11 a deferral beside a Met verdict is an error",
         lambda r: _defer(r), "a deferral defers a finding")
    # A pass carrying a deferral it does not rest on: §4 offers exactly two
    # pass words, and neither fits — plain READY forbids a nonzero deferral
    # count, and READY-WITH-DEFERRALS requires the F2 limb to be the
    # deferred one. The record is internally inconsistent, so the verdict
