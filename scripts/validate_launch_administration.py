def param_block_bytes(instrument_text: bytes):
    """§8's bytes: from the '## 8.' heading to the next '## ' heading."""
    txt = instrument_text.decode("utf-8", errors="replace")
    m = re.search(r"^## 8\..*$", txt, re.M)
    if not m:
        return None
    rest = txt[m.start():]
    nxt = re.search(r"^## (?!8\.)", rest[1:], re.M)
    return (rest if not nxt else rest[: nxt.start() + 1]).encode("utf-8")


def _norm_ws(s):
    return re.sub(r"\s+", " ", s).strip()


def instrument_version(instrument_text: bytes):
    m = re.search(r"^effective_version:\s*(v[0-9]+\.[0-9]+)",
                  instrument_text.decode("utf-8", errors="replace"), re.M)
    return m.group(1) if m else None


def launch_target_forms(pb_text):
    m = re.search(r"LAUNCH_TARGET:\s*>\n((?:[ \t]+\S[^\n]*\n)+)", pb_text)
    lt = _norm_ws(m.group(1)) if m else _norm_ws(pb_text)
    return (lt.rstrip("."), lt.split(". ")[0].rstrip("."))


def _yaml_list(pb_text, key):
    """`KEY: [a, b]` -> `["a","b"]`; `KEY: []` -> `[]`; absent -> `None`.

    **`None` means "this validator could not read the parameter", and every
    caller must treat it as an error rather than a skipped check** (review
    RD-47 finding 1). The empty list and the unreadable parameter are
    different facts: a §8 written in YAML block form instead of flow form
    parsed as absent, the `want is not None` guard skipped LA-3 entirely,
    and a record declaring all six waves required validated clean with a
    `READY FOR` verdict. An unparseable parameter is the one case where
    failing open converts the binding check into a no-op.
    """
    m = re.search(re.escape(key) + r":\s*\[([^\]]*)\]", pb_text)
    if not m:
        return None
    return [x.strip() for x in m.group(1).split(",") if x.strip()]


def _param_path(pb_text, key):
    """The repository path §8 binds to `key`, or `None` if unreadable.

    §8 is a Markdown table, so the row reads

        | `E4_ROUTING_AUTHORITY` | `some/path.md` — commentary |

    and the binding value is the **first code span of the value cell**, not
    the whole cell. Returning `None` when the row cannot be read is
    deliberate: every caller treats it as an error (RD-47 f1).
    """
    m = re.search(r"^\|\s*`" + re.escape(key) + r"`\s*\|\s*`([^`]+)`",
                  pb_text, re.M)
    return m.group(1).strip() if m else None


def e4_cases(pb_text):
    """The `E4_CASES` list, each case's quoted text, in the block's order.

    One of SIX places the validator reads the instrument's own prose —
    `param_block_bytes`, `instrument_version`, `launch_target_forms`,
    `_yaml_list`, `_param_path` and this. RD-47 f9 caught the claim that it
    was "the one place"; v2.1 replaced it with "five", and the same commit's
    own `LA-3b` repair added the sixth. The count is stated here, beside the
    population it counts, and nowhere else (RD-56 f9).

    Like the other five it is bounded and fail-closed by construction: it starts at the
    `E4_CASES` marker and takes numbered, double-quoted items only while
    their numbers run consecutively from 1, so the walk terminates at the
    first thing that is not the next case rather than wandering into the
    rest of §8. It returns None when it finds no case at all, and LA-10
    treats that as an error — never as "no cases to check". Reading the
    instrument, whose digest the record binds, is categorically different
    from parsing a generated report as authority: the bytes are pinned
    before the read, and a mismatch in count or text is an error either way.
    """
    m = re.search(r"`E4_CASES`", pb_text)
    if not m:
        return None
    out, expect = [], 1
    for item in re.finditer(r"^(\d+)\.[ \t]+\"(.*?)\"",
                            pb_text[m.start():], re.S | re.M):
        if int(item.group(1)) != expect:
            break
        out.append(_norm_ws(item.group(2)))
        expect += 1
    return out or None


# ==========================================================================
# validation
# ==========================================================================
def validate(record_path, schema_path=None, prior_path=None, _git=None):
    """Returns (errors, notes, computed) — computed carries the verdict and
    the trend figures. `_git` forces git checks on/off for fixtures."""
    errors, notes = [], []
    if _git is None:
        _git = _git_available()

    schema_path = Path(schema_path or DEFAULT_SCHEMA)
    try:
        schema = _load_json(Path(schema_path).read_text())
    except (OSError, ValueError) as exc:
        return ([f"LA-1: schema unreadable at {schema_path}: {exc}"], notes,
                {})
    # RD-56 f3 — `--schema` was bound to nothing, so `--schema weak.json`
    # containing `{"type": "object"}` turned LA-1 off entirely and the tool
    # still printed a gate result. The flag stays (an operator may want to
    # try a proposed schema), but a record validated against anything other
    # than the committed schema is an INVALID record, and therefore — via
    # §4's fourth eligibility limb — an ineligible one.
    if Path(schema_path).resolve() != Path(DEFAULT_SCHEMA).resolve():
        errors.append(
            f"LA-1: the record was validated against {schema_path}, not the "
            f"committed schema {Path(DEFAULT_SCHEMA).name} — a record is "
            "conformant to the schema the instrument binds or it is not a "
            "record (§5). Use this only for inspection")
    audit = []
    _audit_root_is_a_record_schema(schema, audit)
    _audit_schema(schema, "#", audit)
    if audit:
        return (errors + ["LA-1: " + a for a in audit], notes, {})

    try:
        raw = Path(record_path).read_text()
    except OSError as exc:
        return ([f"LA-1: record unreadable: {exc}"], notes, {})
    try:
        rec = _load_json(raw)
    except ValueError as exc:
        return ([f"LA-1: record is not valid JSON: {exc}"], notes, {})

    # ---- LA-1 schema conformance ----------------------------------------
    schema_errs = []
    _instance_errors(rec, schema, schema, "$", schema_errs)
    errors.extend("LA-1: " + e for e in schema_errs)
    if schema_errs:
        # Every later check indexes fields by name; running them over a
        # record that failed its shape produces noise, not findings.
        return (errors, notes, {})

    commit = rec["repository_commit"]
    rows = {q["question_id"]: q for q in rec["question_results"]}

    # ---- LA-4 roster ----------------------------------------------------
    seen = [q["question_id"] for q in rec["question_results"]]
    dupes = sorted({q for q in seen if seen.count(q) > 1})
    if dupes:
        errors.append("LA-4: question ID(s) answered more than once: "
                      + ", ".join(dupes) + " — a duplicate row would enter "
                      "the computed columns twice")
    missing = [q for q in ROSTER if q not in rows]
    if missing:
        errors.append("LA-4: question row(s) missing: " + ", ".join(missing)
                      + " — absence of a question is never a pass, and a "
                      "record short of the roster cannot support a gate "
                      "decision")
    extra = sorted(set(seen) - ROSTER_SET)
    if extra:
        errors.append("LA-4: row ID(s) outside the roster: "
                      + ", ".join(extra))

    # ---- LA-2 / LA-3 identity and binding -------------------------------
    pb_text = None
    if _git:
        if not _commit_exists(commit):
            errors.append(f"LA-2: named commit {commit} does not exist in "
                          "this repository — every citation is anchored to "
                          "it")
        else:
            blob = _git_show(commit, rec["instrument"]["path"])
            if blob is None:
                errors.append(
                    f"LA-2: instrument `{rec['instrument']['path']}` is not "
                    f"committed at {commit} — an administration against an "
                    "uncommitted instrument binds nothing")
            else:
                got = hashlib.sha256(blob).hexdigest()
                if got != rec["instrument"]["sha256"]:
                    errors.append(
                        "LA-2: instrument digest mismatch — the record "
                        f"quotes {rec['instrument']['sha256'][:12]}…, the "
                        f"committed instrument is {got[:12]}…")
                ver = instrument_version(blob)
                if ver is None:
                    errors.append(
                        "LA-2: the instrument committed at "
                        f"{commit} declares no `effective_version:` this "
                        "validator can read — the version binding is "
                        "Unknown, and an unreadable parameter is an error, "
                        "never a skipped check (RD-47 f1)")
                elif ver != rec["instrument"]["version"]:
                    errors.append(
                        f"LA-2: the record declares instrument version "
                        f"{rec['instrument']['version']} but the instrument "
                        f"committed at {commit} is {ver}")
                pb = param_block_bytes(blob)
                if pb is None:
                    errors.append("LA-2: the committed instrument has no §8 "
                                  "parameter block to digest")
                else:
                    gotp = hashlib.sha256(pb).hexdigest()
                    if gotp != rec["parameter_block_sha256"]:
                        errors.append(
                            "LA-2: parameter-block digest mismatch — the "
                            f"record quotes "
                            f"{rec['parameter_block_sha256'][:12]}…, §8 at "
                            f"the named commit is {gotp[:12]}…")
                    pb_text = pb.decode("utf-8", errors="replace")
                    forms = launch_target_forms(pb_text)
                    tgt = _norm_ws(rec["launch_target"]).rstrip(".")
                    if tgt not in forms:
                        errors.append(
                            f"LA-3: the record's launch target {tgt[:60]!r}… "
                            "is not the parameter block's LAUNCH_TARGET "
                            "(whitespace-normalized; its first sentence "
                            "suffices) — a fragment does not name the target "
                            "§8 binds")
                    for key, field in (("REQUIRED_WAVES", "required_waves"),
                                       ("DEFERRED_WAVES", "deferred_waves")):
                        want = _yaml_list(pb_text, key)
                        if want is None:
                            errors.append(
                                f"LA-3: §8 at {commit} declares no `{key}` "
                                "this validator can read (it expects flow "
                                f"form, `{key}: [ … ]`). The wave binding is "
                                "Unknown, and Unknown is an error here — "
                                "skipping it would let a record declare any "
                                "wave set and still pass (RD-47 f1)")
                        elif want != rec[field]:
                            errors.append(
                                f"LA-3: {field} is {rec[field]!r} but §8's "
                                f"{key} is {want!r} — the administration "
                                "must be bound to the parameters it names")
                    # LA-3b — the routing authority the record restates is
                    # bound to §8 like every other parameter it quotes. A
                    # figure quoted outside its owning artifact goes stale
                    # silently (RD-47 f7).
                    want_ra = _param_path(pb_text, "E4_ROUTING_AUTHORITY")
                    got_ra = _norm_ws(
                        rec.get("e4", {}).get("routing_authority", ""))
                    if want_ra is None:
                        errors.append(
                            f"LA-3b: §8 at {commit} declares no "
                            "`E4_ROUTING_AUTHORITY` this validator can read")
                    elif got_ra and got_ra != want_ra:
                        errors.append(
                            f"LA-3b: the record's E4 routing authority "
                            f"{got_ra!r} is not §8's {want_ra!r} — E4 is "
                            "judged against the authority §8 binds, not one "
                            "the record names")
    else:
        notes.append("LA-2: git unavailable — identity, binding, E4 case "
                     "text and deferral-citation existence were NOT "
                     "verified; this record is not fully validated")

    # ---- LA-5 / LA-6 per-row discipline ---------------------------------
    for qid in ROSTER:
        row = rows.get(qid)
        if row is None:
            continue
        v, scope = row["verdict"], row["launch_scope"]
        if (v == SCOPED) != (scope == "deferred-wave-only"):
            errors.append(
                f"LA-5: {qid} carries verdict {v!r} beside launch_scope "
                f"{scope!r} — the scoped verdict and the scoped field are "
                "authored independently precisely so they must agree")
        if v == SCOPED and qid[0] not in "ABCD":
            errors.append(
                f"LA-5: {qid} carries the scoped verdict — lawful only in "
                "A–D (instrument §2/§4)")
        if v == MET and not row["evidence"]:
            errors.append(f"LA-6: {qid} is Met with no evidence entry — an "
                          "unsupported Met is recorded as Unknown")
        if v in (NOT_MET, SCOPED) and not row["counterexample"]:
            errors.append(f"LA-6: {qid} is {v!r} with no counterexample — a "
                          "Not met names the passage that fails or the "
                          "sweep, with its denominator, that shows absence")
        if v != UNKNOWN:
            for f in ("unknown_reason", "unknown_settlement"):
                if row[f] is not None:
                    errors.append(f"LA-6: {qid} is {v!r} but carries "
                                  f"{f} — the field belongs to Unknown")
        else:
            for f in ("unknown_reason", "unknown_settlement"):
                if not row[f] or _is_placeholder(row[f]):
                    errors.append(
                        f"LA-6: {qid} is Unknown with no {f} — §4 requires "
                        "every Unknown to carry what would settle it")
        if v not in (NOT_MET, SCOPED) and row["counterexample"] is not None:
            errors.append(f"LA-6: {qid} is {v!r} but carries a "
                          "counterexample — the field belongs to a Not met")
        if _is_placeholder(row["falsification_attempt"]):
            errors.append(f"LA-6: {qid}'s falsification_attempt asserts "
                          "emptiness — a verdict that survived no attempt "
                          "to break it is not credible (§2)")
        for i, ev in enumerate(row["evidence"]):
            if not commit.startswith(ev["commit"]) and \
                    not ev["commit"].startswith(commit):
                errors.append(
                    f"LA-6: {qid} evidence[{i}] is anchored to "
                    f"{ev['commit']} but the record names {commit} — "
                    "evidence quoted from any other version is void (§2)")
            # RD-47 f8: deferral paths were existence-checked and evidence
            # paths were not, though evidence is what a verdict rests on. A
            # fabricated filename passed clean. Quote *truthfulness* stays
            # the reader's job and is documented as content-blind; the file
            # existing at the named commit is mechanical, and now checked.
            elif _git:
                pth = ev["path"]
                rel = pth[2:] if pth.startswith("./") else pth
                if _path_kind(commit, rel) != "blob":
                    errors.append(
                        f"LA-6: {qid} evidence[{i}] cites {pth!r}, which is "
                        f"not a file at {commit} — a quote from a file that "
                        "does not exist is not evidence")

    # ---- LA-7 E1 rollup --------------------------------------------------
    if "E1" in rows and rows["E1"]["verdict"] == MET:
        bad = [q for q in E1_SUBROWS
               if q in rows and rows[q]["verdict"] != MET]
        if bad:
            errors.append("LA-7: E1 rolls up Met over non-Met sub-verdicts: "
                          + ", ".join(bad) + " — E1 is Met only when all "
                          "five are")

    # ---- LA-8 scoped disclosure -----------------------------------------
    scoped_rows = [q for q in ROSTER
                   if q in rows and rows[q]["verdict"] == SCOPED]
    findings_by_q = {}
    for f in rec["deferred_wave_findings"]:
        findings_by_q.setdefault(f["question_id"], []).append(f)
    if scoped_rows and not rec["deferred_wave_findings"]:
        errors.append(
            f"LA-8: {len(scoped_rows)} scoped row(s) and no deferred-wave "
            "finding — the record asserts a scoped defect exists and that "
            "none exists")
    for q in scoped_rows:
        fs = findings_by_q.get(q, [])
        if not fs:
            errors.append(f"LA-8: {q} is scoped but no deferred-wave "
                          "finding names it — the disclosure is the scoped "
                          "form's honesty, so it is checked, not trusted")
        for f in fs:
            if f["blocking_conditions_met"]:
                errors.append(
                    f"LA-8: {q}'s deferred-wave finding meets §4 blocking "
                    "condition(s) "
                    + ", ".join(f["blocking_conditions_met"])
                    + " — a defect meeting any of the five blocks the "
                    "verdict and cannot be rendered scoped")
    for f in rec["deferred_wave_findings"]:
        if f["wave"] not in rec["deferred_waves"]:
            errors.append(
                f"LA-8: a deferred-wave finding names wave {f['wave']!r}, "
                f"which is not in deferred_waves {rec['deferred_waves']!r}")

    # ---- LA-9 E3 ---------------------------------------------------------
    e3 = rec["e3"]
    reopen = e3["reopen_items"]
    if "E3" in rows:
        if rows["E3"]["verdict"] == MET:
            if not e3["concepts"] or not e3["trace_rows"]:
                errors.append(
                    "LA-9: E3 is Met without the credibility protocol's "
                    "concept enumeration and trace table — an empty reopen "
                    "list without the trace is Unknown, not Met (§3)")
            traced = {t["concept"] for t in e3["trace_rows"]}
            untraced = [c for c in e3["concepts"] if c not in traced]
            if untraced:
                errors.append(
                    "LA-9: E3 is Met with concept(s) traced to no shape "
                    "artifact: " + ", ".join(untraced))
            if reopen:
                errors.append(
                    f"LA-9: E3 is Met beside {len(reopen)} reopen item(s) — "
                    "§3's own rule is that a non-empty list makes 'ready' "
                    "false regardless of every other verdict")

    # ---- LA-10 E4 --------------------------------------------------------
    e4 = rec["e4"]
    results = e4["fixed_case_results"]
    idx = [r["case_index"] for r in results]
    if sorted(idx) != list(range(1, len(idx) + 1)):
        errors.append(f"LA-10: E4 case indices are {sorted(idx)!r} — the "
                      "fixed cases are answered once each, in the parameter "
                      "block's own numbering")
    if pb_text is not None:
        cases = e4_cases(pb_text)
        if cases is None:
            errors.append("LA-10: §8 at the named commit has no E4_CASES "
                          "block to bind the fixed cases to")
        else:
            if len(results) != len(cases):
                errors.append(
                    f"LA-10: {len(results)} E4 result(s) against "
                    f"{len(cases)} fixed case(s) in §8 — E4's comparability "
                    "across administrations is the whole point of fixing "
                    "them")
            for r in results:
                i = r["case_index"]
                if 1 <= i <= len(cases):
                    if _norm_ws(r["case_text"]) != cases[i - 1]:
                        errors.append(
                            f"LA-10: E4 case {i}'s text does not match §8's "
                            "own — a verdict rendered against a paraphrased "
                            "case is void (§2)")
    disagree = [r["case_index"] for r in results
                if r["routing_authority_says"] != "silent"
                and r["routing_authority_says"] != r["reviewer_classification"]]
    if disagree and "E4" in rows and rows["E4"]["verdict"] == MET:
        errors.append(
            "LA-10: E4 is Met while the reviewer and the routing authority "
            "disagree on case(s) " + ", ".join(str(i) for i in disagree)
            + " — disagreement with the project's routing is a fail")
    notes_blob = " ".join(rec["operationalization_notes"]).lower()
    for r in results:
        if r["routing_authority_says"] == "silent" and \
                r["needed_by_launch_target"]:
            if f"e4 case {r['case_index']}" not in notes_blob:
                errors.append(
                    f"LA-10: the routing authority is silent on E4 case "
                    f"{r['case_index']}, which the launch target needs "
                    "routed, and no operationalization note records it — §3 "
                    "makes that silence a finding in its own right")

    # ---- LA-11 deferrals -------------------------------------------------
    # Which deferrals carry a citation that actually RESOLVED. §4's
    # READY-WITH-DEFERRALS predicate ends "AND the citation resolves", and
    # the branch was selected from the deferral COUNT alone, so a record
    # with an unresolvable citation still computed the pass word beside its
    # own error (RD-56 f8).
    resolved_deferrals = set()
    for d in rec["owner_deferrals"]:
        qid = d["question_id"]
        if qid not in ROSTER_SET:
            errors.append(f"LA-11: deferral names {qid!r}, which is not a "
                          "roster question")
        elif qid in NEVER_DEFERRABLE:
            errors.append(
                f"LA-11: a deferral is claimed against {qid} — §4 makes "
                "every conjunct but F2 non-deferrable, each carrying its "
                "own rationale for blocking")
        cite = d["decision_citation"].strip()
        if re.fullmatch(r"(?:P|D|B)-\d+[a-z]?(?:\([a-z]\))?", cite):
            errors.append(
                f"LA-11: {cite!r} grants no deferral — P-n names the queue "
                "of decisions *not* made, D-n a semantic-delta item, B-n "
                "review-finding numbering. A deferral is claimed by citing "
                "a made decision")
        elif re.fullmatch(r"SDR-\d+[a-z]?(?:\([a-z]\))?", cite):
            if _git and not _sdr_exists(cite, commit):
                errors.append(
                    f"LA-11: {cite} names no decision in {DECISIONS_HOME} "
                    f"at {commit}")
            else:
                resolved_deferrals.add(qid)
        elif _git and _path_kind(
                commit, cite[2:] if cite.startswith("./") else cite):
            # Path-ness is decided by RESOLVING the citation against the
            # commit, never by `"/" in cite` (RD-47 f5) — that test rejected
            # a real root-level file and accepted anything with a slash in
            # it, which is how `.beads/issues.jsonl` became a warrant.
            #
            # A PREFIX strip, never `lstrip("./")` — that takes a character
            # SET and would eat the leading dot of `.syzygy/…`, turning
            # every governed path into a non-existent one.
            rel = cite[2:] if cite.startswith("./") else cite
            kind = _path_kind(commit, rel)
            if kind != "blob":
                errors.append(f"LA-11: the deferral path {cite!r} is a "
                              f"{kind}, not a file — a directory grants "
                              "nothing")
            elif not rel.startswith(DECISIONS_HOME + "/"):
                # RD-47 f4. A deferral is a WARRANT, and only a recorded
                # owner decision is one. The queue of decisions the owner
                # has NOT made was granting deferrals through this branch,
                # as was a Beads issue — both are records that a question is
                # open, which is the opposite of the thing being cited.
                errors.append(
                    f"LA-11: the deferral citation {cite!r} does not live "
                    f"in {DECISIONS_HOME}/ — a deferral is warranted by a "
                    "made owner decision, and nothing else grants one")
            else:
                why = _non_warrant_reason(commit, rel)
                if why:
                    errors.append(
                        f"LA-11: {cite!r} {why} — a deferral is warranted by "
                        "a made owner decision and by nothing else (LA-11's "
                        "own words: \"a made decision, never a queue "
                        "entry\")")
                else:
                    resolved_deferrals.add(qid)
        elif "/" in cite or cite.endswith((".md", ".txt", ".yaml", ".json")):
            # Shaped like a path, and did not resolve. Distinguished from
            # the not-a-citation case below so the error names the actual
            # defect: a citation that points nowhere is a different mistake
            # from a citation that was never a citation.
            errors.append(f"LA-11: the deferral path {cite!r} does "
                          f"not exist at {commit}")
        else:
            errors.append(
                f"LA-11: {cite!r} is neither a repository path nor an SDR-n "
                "identifier — label wording is not a citation")
        if qid in rows and rows[qid]["verdict"] == MET:
            errors.append(
                f"LA-11: a deferral is claimed against {qid}, whose verdict "
                "is Met — a deferral defers a finding, and this row records "
                "none. A vacuous deferral would still convert a plain pass "
                "into READY-WITH-DEFERRALS")
        if _is_placeholder(d["bounded_reduction_plan"]):
            errors.append(
                f"LA-11: the deferral on {qid} carries no bounded reduction "
                "plan — §4 grants an F2 deferral only against one (maximum "
                "new meta-artifacts, artifacts to retire, stop condition)")

    # ---- LA-13 administration integrity ---------------------------------
    if rec["formal"]:
        if rec["administration_kind"] != "full":
            errors.append(
                "LA-13: a formal administration is declared with "
                f"administration_kind {rec['administration_kind']!r} — the "
                "gate decision requires a full administration at the named "
                "commit; regressions do not announce themselves (§2)")
        if not rec["reviewer"]["fresh_context"]:
            errors.append("LA-13: a formal administration is declared with "
                          "fresh_context false (§2)")

    # ---- LA-14 G1 --------------------------------------------------------
    if _is_placeholder(rec["g1"]["critic_answer"]):
        errors.append(
            "LA-14: G1's critic answer asserts emptiness — an administration "
            "missing G1 is incomplete and cannot support a gate decision, "
            "and a G1 that answers nothing is that absence wearing the "
            "shape of a presence")

    # ---- LA-15 trend anchoring ------------------------------------------
    prior = rec["prior_record"]
    if prior is not None:
        if prior["date"] > rec["date"]:
            errors.append(
                f"LA-15: the declared prior record is dated {prior['date']}, "
                f"after this administration's {rec['date']} — a later record "
                "is not a prior one")
        if _git:
            if not _commit_exists(prior["repository_commit"]):
                errors.append("LA-15: the prior record's commit "
                              f"{prior['repository_commit']} does not exist")
            elif _commit_exists(commit) and not _is_ancestor(
                    prior["repository_commit"], commit):
                errors.append(
                    f"LA-15: the prior record's commit "
                    f"{prior['repository_commit']} is not an ancestor of "
                    f"{commit} — a record from a divergent history is a "
                    "stale prior, and the trend delta computed against it "
                    "would be meaningless")
    if prior_path is not None:
        if prior is None:
            errors.append("LA-15: --prior was supplied but the record "
                          "declares prior_record: null")
        else:
            try:
                pj = _load_json(Path(prior_path).read_text())
            except (OSError, ValueError) as exc:
                errors.append(f"LA-15: --prior unreadable: {exc}")
                pj = None
            if pj is not None and \
                    pj.get("repository_commit") != prior["repository_commit"]:
                errors.append(
                    "LA-15: --prior names commit "
                    f"{pj.get('repository_commit')} but the record's "
                    f"prior_record names {prior['repository_commit']}")

    # ---- LA-16 pilot recurrence -----------------------------------------
    if rec["formal"] and prior is None:
        prc = rec["pilot_recurrence_check"]
        if not prc["performed"]:
            errors.append(
                "LA-16: this formal administration opens the trend log and "
                "records the §8 PILOT_RECURRENCE_CHECK as not performed — "
                "the pilot's own finding is the one recurrence the log "
                "cannot see")
        if _is_placeholder(prc["method"]):
            errors.append("LA-16: the pilot-recurrence check records no "
                          "method")

    # ---- LA-12 the §4 formula -------------------------------------------
    computed = _compute(rec, rows, prior_path, prior_errors=errors,
                        git_ok=bool(_git),
                        resolved_deferrals=resolved_deferrals)
    errors.extend(computed.pop("_errors"))
    return errors, notes, computed


def _compute(rec, rows, prior_path, prior_errors=(), git_ok=True,
             resolved_deferrals=None):
    """The §4 formula and the §6 trend figures, computed from the rows.

    `prior_errors` are the errors every check before LA-12 has already
    raised. They are an *input* because §4's eligibility clause has four
    limbs and the fourth is "and validates without error" — computing
    eligibility without them implements three quarters of a rule while
    reporting it as the whole (RD-55 f1, RD-56 f1, found independently).
    `git_ok` is false when the identity checks could not run at all, which
    is a stronger disqualification than any single error."""
    errs = []
    verdict_of = {q: rows[q]["verdict"] for q in rows}

    n_not_met = sum(1 for q in ROSTER
                    if verdict_of.get(q) == NOT_MET)
    n_scoped = sum(1 for q in ROSTER if verdict_of.get(q) == SCOPED)
    n_unknown = sum(1 for q in ROSTER if verdict_of.get(q) == UNKNOWN)
    n_deferred = len(rec["owner_deferrals"])
    n_reopened = len(rec["reopened_findings"])

    conjuncts = []

    def _c(name, ok, why):
        conjuncts.append((name, bool(ok), why))
        return bool(ok)

    e_all_met = all(verdict_of.get(q) == MET for q in E_ROWS)
    _c("every E question Met", e_all_met,
       ", ".join(f"{q}={verdict_of.get(q)!r}" for q in E_ROWS
                 if verdict_of.get(q) != MET) or "all Met")
    ad_blockers = [q for q in AD_ROWS if verdict_of.get(q) == NOT_MET]
    _c("no plain `Not met` in launch-scope A–D", not ad_blockers,
       ", ".join(ad_blockers) or "none")
    _c("F1 is Met or Unknown", verdict_of.get("F1") in (MET, UNKNOWN),
       f"F1={verdict_of.get('F1')!r}")
    _c("F3 is Met", verdict_of.get("F3") == MET,
       f"F3={verdict_of.get('F3')!r}")
    _c("F4 is Met", verdict_of.get("F4") == MET,
       f"F4={verdict_of.get('F4')!r}")
    # E3's reopen list is a conjunct of readiness in its own right (§3).
    _c("E3's reopen list is empty", not rec["e3"]["reopen_items"],
       f"{len(rec['e3']['reopen_items'])} item(s)")

    core = all(ok for _, ok, _ in conjuncts)

    f2 = verdict_of.get("F2")
    f2_deferrals = [d for d in rec["owner_deferrals"]
                    if d["question_id"] == "F2"]
    f2_met = f2 == MET
    f2_deferred = bool(f2_deferrals)
    # §4: "…AND the citation resolves." `None` means the caller did not run
    # the citation checks (a fixture computing the formula alone); an empty
    # set from a real validation means nothing resolved.
    _f2_citation_resolves = (resolved_deferrals is None
                             or "F2" in resolved_deferrals)
    if f2_deferred and not _f2_citation_resolves:
        errs.append("LA-12: READY-WITH-DEFERRALS requires the F2 deferral's "
                    "citation to resolve (§4), and it did not — a deferral "
                    "whose warrant cannot be found defers nothing")

    if core and f2_met and n_deferred == 0:
        verdict = f"READY FOR {rec['launch_target']}"
        branch = "plain"
    elif core and f2_deferred and n_deferred > 0 and _f2_citation_resolves:
        verdict = "READY-WITH-DEFERRALS"
        branch = "deferrals"
    else:
        verdict = "NOT READY"
        branch = "blocked"

    # ---- eligibility is a SEPARATE question from the formula -------------
    # Three results, and conflating them is how a diagnostic run comes to
    # read like a gate outcome (charter §7.1; reviews RD-47 f11, RD-48 f5).
    #
    #   verdict        what the rows compute        always produced
    #   eligible       may this run be cited as launch evidence?
    #   gate_result    the formal outcome           only when eligible
    #
    # A `delta` record with every row Met printed `READY FOR …`, a §6 trend
    # row carrying it, and `record valid` — with no error and no note —
    # although §2 rejects a delta record as gate evidence. The formula was
    # right; presenting its output as a gate result was not.
    # A pass that rests on any deferral is READY-WITH-DEFERRALS, never plain.
    if branch == "plain" and n_deferred:
        errs.append("LA-12: a plain READY verdict over a nonzero deferral "
                    "count is a contradiction (§4)")
    if branch == "deferrals" and not f2_met and not f2_deferred:
        errs.append("LA-12: READY-WITH-DEFERRALS substitutes exactly the F2 "
                    "limb, and no owner deferral names F2")
    if n_deferred and branch == "blocked" and core:
        errs.append("LA-12: deferrals are declared against a passing core "
                    "with no F2 deferral — the only deferrable limb is F2")

    # ---- new findings versus the prior administration --------------------
    # The CANONICAL RECORD decides what this is compared against — its own
    # `prior_record.path` — never an optional CLI flag (review RD-47 f3).
    # Bound to `--prior` alone, the column could not be computed by the
    # documented path at all: the renderer has no such flag, so every
    # generated report read `n/a (no prior record)` even when the record
    # named one. That is a false claim of absence, which is exactly what
    # VIS-2 forbids. `--prior`, when given, still overrides for inspection.
    #
    # Three distinct outcomes, and they must not collapse into each other:
    #   an integer   the comparison ran
    #   None         no prior is declared — this record opens the log
    #   "unknown"    a prior IS declared and could not be read
    new_findings = None
    src = prior_path
    if src is None and rec.get("prior_record"):
        # RD-56 f6 — this is the only path whose CONTENT is read and
        # arithmetic performed on, and it was the one path not resolved
        # against the repository: `REPO / "../../../forged.json"` escapes,
        # and a hand-written file asserting every row was already `Not met`
        # zeroed the §6 new-findings column with no error raised.
        cand = (REPO / rec["prior_record"]["path"]).resolve()
        try:
            inside = cand.is_relative_to(REPO.resolve())
        except AttributeError:                      # Python < 3.9
            inside = str(cand).startswith(str(REPO.resolve()) + "/")
        src = str(cand) if inside else None
        if not inside:
            errs.append(
                "LA-15: the prior record's path "
                f"{rec['prior_record']['path']!r} resolves outside the "
                "repository — the new-findings column is computed from it, "
                "so it is evidence and must live where evidence lives")
    if src is not None:
        try:
            pj = _load_json(Path(src).read_text())
            pv = {q["question_id"]: q["verdict"]
                  for q in pj.get("question_results", [])}
            newly_not_met = [q for q in ROSTER
                             if verdict_of.get(q) == NOT_MET
                             and pv.get(q) != NOT_MET]
            newly_scoped = [q for q in ROSTER
                            if verdict_of.get(q) == SCOPED
                            and pv.get(q) not in (NOT_MET, SCOPED)]
            new_findings = len(newly_not_met) + len(newly_scoped)
        except (OSError, ValueError):
            new_findings = "unknown"

    # Eligibility is computed LAST, because its fourth limb counts errors —
    # including the LA-12 errors raised above. Placing it earlier is how the
    # rule came to be three-quarters implemented the first time.
    n_err = len(prior_errors) + len(errs)
    ineligible = []
    if not rec["formal"]:
        ineligible.append("`formal: false`")
    if rec["administration_kind"] != "full":
        ineligible.append(f"`administration_kind: "
                          f"{rec['administration_kind']}`")
    if not rec["reviewer"]["fresh_context"]:
        ineligible.append("the reviewer declares no fresh context")
    if n_err:
        ineligible.append(f"the record has {n_err} validation error(s)")
    if not git_ok:
        ineligible.append("git was unavailable, so the identity, binding, "
                          "case-text, deferral and evidence checks did not "
                          "run — an unverified record is not eligible")
    eligible = not ineligible
    gate_result = verdict if eligible else "NO FORMAL GATE RESULT"

    return {
        "_errors": errs,
        "verdict": verdict,
        "eligible": eligible,
        "ineligible_because": ineligible,
        "gate_result": gate_result,
        "branch": branch,
        "conjuncts": conjuncts,
        "not_met": n_not_met,
        "scoped": n_scoped,
        "unknown": n_unknown,
        "deferred": n_deferred,
        "reopened": n_reopened,
        "new_findings": new_findings,
    }


def trend_row(rec, computed):
    """§6's row, generated. The Gate-verdict column carries the *gate result*
    (§4's third outcome), never the row/formula outcome — an ineligible
    administration whose rows all read `Met` must not deposit
    `READY FOR …` into the log F1 is answered from and only from."""
    nf = computed["new_findings"]
    if computed["eligible"]:
        col = computed["gate_result"]
    else:
        col = ("NONE — not eligible; row outcome was "
               + computed["verdict"])
    # Every cell is sanitized, not only the verdict. A `launch_target`
    # differing from §8 by an embedded newline passes LA-3 (which compares
    # whitespace-normalized) and used to split this row across two lines
    # (RD-56 f12); `date` did the same through a pattern anchored with `$`,
    # which matches before a trailing newline.
    def cell(x):
        return str(x).replace("|", "/").replace("\r", " ").replace(
            "\n", " ").strip()

    return "| {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
        cell(rec["date"]), cell(rec["repository_commit"][:7]),
        cell(computed["not_met"]), cell(computed["scoped"]),
        cell(computed["unknown"]), cell(computed["deferred"]),
        cell(computed["reopened"]),
        "n/a (no prior record)" if nf is None else cell(nf),
        cell(col))


