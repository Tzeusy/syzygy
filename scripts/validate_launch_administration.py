#!/usr/bin/env python3
"""Validate a **structured** launch-gate administration record and compute
its verdict and trend row.

Scope, stated so nobody mistakes it: this tool validates the record and
computes its derived figures. Readiness semantics are owned by
`launch-gate-pre-specifications.md` (§4); where this tool applies the §4
formula it is checking the record against the instrument, never deciding
readiness independently of it. A record this tool passes can still support
nothing if the instrument's non-mechanical requirements (fresh context,
family disclosure, a genuine falsification attempt) were not honored —
those live in the record's own fields and the reader's judgment.

**Why this tool exists.** Its predecessor, `launch_gate_results.py`, parsed
a human Markdown report as the machine source of a launch decision. Thirteen
consecutive administrations of that instrument returned `REVISE`, and the
findings converged on one question the Markdown could not answer stably:
*is this line the record's own claim, or a quotation of one?* v2.0 removes
the question rather than answering it again. The canonical record is JSON;
the Markdown is generated by `render_launch_administration.py` and is never
parsed back. There is no Markdown or HTML visibility classifier anywhere in
this file's correctness path.

Checks (each with at least one `--selftest` mutation fixture):

  LA-1  schema conformance against the committed JSON Schema — types, the
        closed verdict vocabulary, required fields, and `additionalProperties:
        false` everywhere, so an unknown key is an error rather than a
        silently ignored one. A `final_verdict` key is rejected here: the
        verdict is computed, and a record that cannot claim one cannot be
        believed about one
  LA-2  identity — the named commit exists; the instrument is committed at
        it; the record's instrument sha256 matches those bytes; the
        parameter-block sha256 matches §8 of those bytes; the declared
        instrument version matches the committed `effective_version`
  LA-3  binding — the record's launch target equals (whitespace-normalized)
        the parameter block's `LAUNCH_TARGET` or its first sentence, and the
        required/deferred wave lists equal the parameter block's
  LA-4  roster — exactly the full question set is answered, once each:
        A1–A6, B1–B5, C1–C7, D1–D4, E1 with its five sub-rows, E2–E6,
        F1–F6. A missing row is an error, never a pass; an extra row is an
        error too, so an invented question cannot enter the computed columns
  LA-5  verdict/scope agreement — `launch_scope: deferred-wave-only` is
        lawful with the scoped verdict and with no other, and the scoped
        verdict only in A–D. The two fields are authored independently and
        cross-checked, so one typo cannot launder a defect out of scope
  LA-6  evidence discipline — `Met` requires at least one evidence entry;
        either `Not met` form requires a counterexample; `Unknown` requires
        both a reason and what would settle it; fields that do not belong to
        the verdict must be null; and every evidence entry is anchored to
        the record's own `repository_commit`
  LA-7  E1 rolls up — `E1` is `Met` only when all five sub-rows are `Met`
  LA-8  scoped rows are disclosed — any scoped row requires a
        `deferred_wave_findings` entry naming that question, and a finding
        that meets any of §4's five blocking conditions cannot support a
        scoped verdict
  LA-9  E3's credibility protocol — `Met` requires the concept enumeration
        and a trace row per concept; a non-empty reopen list forbids `E3 |
        Met` and forbids any READY verdict (§3's self-declared sharpest
        single gate)
  LA-10 E4's fixed cases — one result per `E4_CASES` case, indices exactly
        1..n, each `case_text` equal to the instrument's own case text, so a
        paraphrased case cannot carry a verdict; reviewer/authority
        disagreement forbids `E4 | Met`; and silence over a case the launch
        target needs routed must be recorded in the operationalization notes
  LA-11 deferrals are cited, not asserted — each names a repository path
        that exists at the named commit and is a file, or an `SDR-n` that
        exists in the decisions home; `P-n` (the queue of decisions *not*
        made), `D-n` (a delta item) and `B-n` (review-finding numbering)
        grant nothing; and no deferral may be claimed against a conjunct §4
        calls never deferrable
  LA-12 the §4 formula, computed — both pass branches run the full conjunct
        battery: every E row `Met`, no plain `Not met` in launch-scope A–D,
        F1 `Met`-or-`Unknown`, F3 `Met`, F4 `Met`. Plain `READY FOR`
        additionally requires F2 `Met` and zero deferrals;
        `READY-WITH-DEFERRALS` substitutes exactly the F2 limb with an
        owner-cited deferral and requires a nonzero deferral count
  LA-13 administration integrity — a `formal` administration must be
        `full` and must be fresh-context (§2). It does NOT reject a
        `formal: false` delta record: such a record is lawful, and what
        stops it supporting a gate decision is the eligibility computation,
        which yields `NO FORMAL GATE RESULT` for it. *(Corrected — review
        RD-48 finding 5 found this entry claiming "a `delta` record can
        never support a gate decision", while the check gates entirely on
        `rec["formal"]`. A record with `formal: false`, kind `delta` and
        every row `Met` printed a READY verdict and a trend row carrying
        it, with no error and no note. The check was right and this
        sentence was wrong; the missing half was eligibility, now
        computed and printed separately from the formula.)*
  LA-14 G1 — present, answered, and never a verdict row. The roster (LA-4)
        already refuses a `G1` row; this check refuses a placeholder answer,
        because a G1 section that says "none" is the absence LA-4 would have
        caught wearing the shape of a presence
  LA-15 trend anchoring — a declared prior record must exist, its commit
        must be an ancestor of this record's commit, and its date must not
        follow this one; a `--prior` file must be the record `prior_record`
        names
  LA-16 the pilot-recurrence check (§8 `PILOT_RECURRENCE_CHECK`) is
        performed and its method recorded, on any formal administration
        that opens the trend log

Every free-text field this tool relies on is checked against a placeholder
lexicon: a value whose tokens are all placeholders ("none", "n/a", "tbd")
asserts emptiness, and asserting emptiness is not answering. Presence tests
elsewhere are content-blind by design — the truthfulness of an evidence
quote stays with the reader.

Usage:
  python3 scripts/validate_launch_administration.py <record.json>
      [--schema launch-gate-administration.schema.json]
      [--prior <record.json>] [--trend-row]
  python3 scripts/validate_launch_administration.py --selftest
"""

