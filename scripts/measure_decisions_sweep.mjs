#!/usr/bin/env node
// Whole `statementsFor` calls over the decisions directory, old tree against new, for syzygy-bpyt.8.20's acceptance criterion 1.
// Evidence tool, not a check and not authority.
//
//   (in each tree) npm ci && npx tsc -b packages/polaris-generation-consent packages/polaris-dossier
//   node scripts/measure_decisions_sweep.mjs --old <tree> --new <tree> --out <file.json> [--rounds <n>] [--repository <id>]
//
// Each sample is one fresh `node` process that imports one tree's compiled dossier gate sources and makes one
// `providerStatements.statementsFor(<repository>)` call over `--old`'s checkout (both trees read the same records), timed inside the
// process from just before the call to just after it. The rounds alternate which tree goes first, and each sample records the host's
// one-minute load average just before and just after it, its start time, and the sha256 of the answer's JSON. The bound the bead holds
// the new tree to is computed and stated, never asserted: every new sample at most 5000 ms at a one-minute load of at most 30, and the
// median of the paired new/old ratios at most 0.4.

import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT = fileURLToPath(import.meta.url);
const SCRIPT_REL = 'scripts/measure_decisions_sweep.mjs';
const GATE = 'packages/polaris-dossier/dist/gate-sources.js';
const NOW = Date.parse('2026-10-22T12:00:00Z');
const BOUND = { newMsMax: 5000, atLoad1Max: 30, medianRatioMax: 0.4 };
const sha256 = text => createHash('sha256').update(text, 'utf8').digest('hex');

if (process.argv[2] === '--child') {
  const [tree, root, repository] = process.argv.slice(3);
  const gate = await import(pathToFileURL(path.join(tree, GATE)).href);
  const sources = gate.createPackageGateSources({ root, now: () => NOW });
  const started = performance.now();
  const answer = await sources.providerStatements.statementsFor(repository);
  const ms = performance.now() - started;
  process.stdout.write(`${JSON.stringify({ ms, answerSha256: sha256(JSON.stringify(answer)) })}\n`);
} else {
  process.exitCode = main(process.argv.slice(2));
}

function main(argv) {
  const arg = flag => (argv.includes(flag) ? argv[argv.indexOf(flag) + 1] : undefined);
  const oldTree = arg('--old'), newTree = arg('--new'), out = arg('--out'), rounds = Number(arg('--rounds') ?? 8), repository = arg('--repository') ?? 'redis-redis';
  if (oldTree === undefined || newTree === undefined || out === undefined) {
    process.stderr.write('usage: node scripts/measure_decisions_sweep.mjs --old <tree> --new <tree> --out <file.json> [--rounds <n>] [--repository <id>]\n');
    return 2;
  }
  const trees = { old: path.resolve(oldTree), new: path.resolve(newTree) }, root = trees.old;
  const git = (tree, ...args) => execFileSync('git', ['-C', tree, ...args], { encoding: 'utf8' }).trim();
  const sample = (role, round) => {
    const load1Before = os.loadavg()[0], startedAt = new Date().toISOString();
    const run = spawnSync(process.execPath, [SCRIPT, '--child', trees[role], root, repository], { encoding: 'utf8' });
    if (run.status !== 0) throw new Error(`the ${role} sample failed: ${run.stderr}`);
    const { ms, answerSha256 } = JSON.parse(run.stdout);
    const row = { round, role, ms: Math.round(ms), load1Before: Number(load1Before.toFixed(2)), load1After: Number(os.loadavg()[0].toFixed(2)), startedAt, answerSha256 };
    process.stderr.write(`${round} ${role} ${row.ms} ms load1 ${row.load1Before}\n`);
    return row;
  };
  const samples = [];
  for (let round = 0; round < rounds; round += 1) {
    for (const role of round % 2 === 0 ? ['old', 'new'] : ['new', 'old']) samples.push(sample(role, round));
  }
  const of = role => samples.filter(s => s.role === role);
  const ratios = Array.from({ length: rounds }, (_, round) => samples.find(s => s.round === round && s.role === 'new').ms / samples.find(s => s.round === round && s.role === 'old').ms).sort((a, b) => a - b);
  const median = ratios.length % 2 === 1 ? ratios[(ratios.length - 1) / 2] : (ratios[ratios.length / 2 - 1] + ratios[ratios.length / 2]) / 2;
  const loads = samples.flatMap(s => [s.load1Before, s.load1After]);
  const newMsMax = Math.max(...of('new').map(s => s.ms)), load1Max = Math.max(...loads);
  const document = {
    schema: 'decisions-sweep-measurement/1',
    bead: 'syzygy-bpyt.8.20',
    text: 'Evidence record, not authority: whole statementsFor calls over one decisions directory, old tree against new, each in a fresh process, with the host load beside each sample. Generated by the script named here; do not edit.',
    script: { path: SCRIPT_REL, sha256: sha256(fs.readFileSync(SCRIPT, 'utf8')) },
    trees: Object.entries(trees).map(([role, tree]) => ({
      role, commit: git(tree, 'rev-parse', 'HEAD'), clean: git(tree, 'status', '--porcelain', '--untracked-files=no') === '',
      packageReaderJsSha256: sha256(fs.readFileSync(path.join(tree, 'packages/polaris-generation-consent/dist/package-reader.js'), 'utf8')),
      gateSourcesJsSha256: sha256(fs.readFileSync(path.join(tree, GATE), 'utf8')),
    })),
    recordsRoot: 'old',
    call: { reader: 'createPackageGateSources(...).providerStatements.statementsFor', repository, now: new Date(NOW).toISOString() },
    host: { cpus: os.cpus().length, node: process.version, platform: `${os.platform()} ${os.release()}` },
    rounds,
    samples,
    summary: {
      oldMs: { min: Math.min(...of('old').map(s => s.ms)), max: Math.max(...of('old').map(s => s.ms)) },
      newMs: { min: Math.min(...of('new').map(s => s.ms)), max: newMsMax },
      load1: { min: Math.min(...loads), max: load1Max },
      pairedRatioMedian: Number(median.toFixed(3)),
      pairedRatios: ratios.map(r => Number(r.toFixed(3))),
      answersAgree: new Set(samples.map(s => s.answerSha256)).size === 1,
    },
    bound: { ...BOUND, holds: newMsMax <= BOUND.newMsMax && load1Max <= BOUND.atLoad1Max && median <= BOUND.medianRatioMax, note: 'computed over every sample; a sample whose load exceeds atLoad1Max is outside the bound\'s conditions, and the record then does not hold it' },
  };
  fs.writeFileSync(out, `${JSON.stringify(document, null, 1)}\n`);
  process.stderr.write(`old ${document.summary.oldMs.min}-${document.summary.oldMs.max} ms, new ${document.summary.newMs.min}-${newMsMax} ms, median ratio ${document.summary.pairedRatioMedian}, load1 ${document.summary.load1.min}-${load1Max}, bound holds: ${document.bound.holds}\n`);
  return document.summary.answersAgree ? 0 : 1;
}
