#!/usr/bin/env python3
"""Rule-6 mutants of the recorder line slot (syzygy-bpyt.8.17). Evidence tool, not a check and not authority.

usage: python3 -I scripts/run_line_slot_rule6_mutants.py TREE --out OUT.json

TREE must be a clean checkout. The script runs the tests named `syzygy-bpyt.8.17` in recorder-template.test.ts unmutated, then for each
mutant below replaces the one occurrence of `old` in recorder-template.ts by `new`, runs `npx vitest run --project
@syzygy/polaris-generation-consent --reporter=json --outputFile=<tmp> -t syzygy-bpyt.8.17 <test file>` in TREE, and restores the file
from git. A mutant is killed when a selected test fails. A run that reports no test is re-run once and, if it still reports none,
recorded as `errored`, never as killed. OUT.json names the commit, the sha256 of the mutated and test files at HEAD, the command, and per
mutant its `old`/`new`, the expected outcome, the failed tests each with its first error line (a vm timeout reads `Script execution timed
out`; a load timeout would read `Test timed out`), and the run's wall time. It writes only OUT.json, and the mutated file only while a
mutant runs."""
import datetime, hashlib, json, os, subprocess, sys, tempfile, time

SCRIPT = 'scripts/run_line_slot_rule6_mutants.py'
FILE = 'packages/polaris-generation-consent/src/recorder-template.ts'
TESTS = 'packages/polaris-generation-consent/src/recorder-template.test.ts'
PROJECT = '@syzygy/polaris-generation-consent'
SELECTOR = 'syzygy-bpyt.8.17'
SLOT = r"line: '[^\\S\\r\\n]*\\S[^\\r\\n]*',"
TIMING = 'the line slot (syzygy-bpyt.8.17) refuses a record that fails after four long line slots within a second'
MUTANTS = [
    ('restore-ambiguous', r"line: '[^\\r\\n]*\\S[^\\r\\n]*',", 'killed', 'the pattern before this bead: same lines, one way per non-space'),
    ('lead-allows-cr', r"line: '[^\\S\\n]*\\S[^\\r\\n]*',", 'killed', 'the leading run admits CR'),
    ('tail-allows-cr', r"line: '[^\\S\\r\\n]*\\S[^\\n]*',", 'killed', 'the tail admits CR'),
    ('lead-ascii-blanks', r"line: '[ \\t]*\\S[^\\r\\n]*',", 'killed', 'the leading run admits only space and tab'),
    ('lead-dropped', r"line: '\\S[^\\r\\n]*',", 'killed', 'no leading run: a line must start with a non-space'),
    ('non-space-any', r"line: '[^\\S\\r\\n]*[^\\r\\n][^\\r\\n]*',", 'killed', 'a blank line is accepted'),
    ('tail-lazy', r"line: '[^\\S\\r\\n]*\\S[^\\r\\n]*?',", 'killed', 'same lines, but a slot followed by more template takes the shortest value the rest accepts'),
    ('lead-lazy', r"line: '[^\\S\\r\\n]*?\\S[^\\r\\n]*',", 'survived', 'equivalent: a lazy run of spaces still stops only at the first non-space, so the lines, the captures and the one way are the same'),
]

args = sys.argv[1:]
if len(args) != 3 or args[1] != '--out': sys.exit(__doc__.split('\n\n')[1])
tree, out_path = os.path.abspath(args[0]), args[2]
sha = lambda b: hashlib.sha256(b).hexdigest()
def run(cmd): return subprocess.run(cmd, cwd=tree, capture_output=True)
def at_head(path): return run(['git', 'show', f'HEAD:{path}']).stdout
def clean(): return run(['git', 'status', '--porcelain', '--untracked-files=no']).stdout.strip() == b''

if not clean(): sys.exit('tree not clean')
COMMAND = ['npx', 'vitest', 'run', '--project', PROJECT, '--reporter=json', '--outputFile=<tmp>', '-t', SELECTOR, TESTS]

def vitest():
    for _attempt in range(2):
        with tempfile.TemporaryDirectory() as tmp:
            report = os.path.join(tmp, 'report.json')
            started = time.monotonic()
            run([f'--outputFile={report}' if part == '--outputFile=<tmp>' else part for part in COMMAND])
            seconds = round(time.monotonic() - started, 1)
            data = json.load(open(report)) if os.path.exists(report) else {}
        results = [a for f in data.get('testResults', []) for a in f.get('assertionResults', [])]
        ran = [a for a in results if a['status'] in ('passed', 'failed')]
        if ran: break
    failed = [{'test': a['fullName'], 'firstErrorLine': (a.get('failureMessages') or [''])[0].split('\n')[0]} for a in ran if a['status'] == 'failed']
    return {'selected': len(ran), 'passed': len(ran) - len(failed), 'failed': sorted(failed, key=lambda f: f['test']), 'wallSeconds': seconds}

text = open(os.path.join(tree, FILE), encoding='utf8').read()
if text.count(SLOT) != 1: sys.exit(f'{FILE} does not carry the slot exactly once')
out = {
    'schema': 'line-slot-rule6/1', 'bead': SELECTOR,
    'text': 'Evidence record, not authority: rule-6 mutants of the recorder line slot, each run against the tests the selector picks. Generated by the script named here; do not edit.',
    'script': {'path': SCRIPT, 'sha256': sha(at_head(SCRIPT))},
    'subject': {'commit': run(['git', 'rev-parse', 'HEAD']).stdout.decode().strip(), 'file': FILE, 'fileSha256': sha(at_head(FILE)), 'tests': TESTS, 'testsSha256': sha(at_head(TESTS))},
    'command': ' '.join(COMMAND), 'selector': SELECTOR, 'timingTest': TIMING,
    'ranAt': datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds'),
    'baseline': vitest(), 'mutants': [],
}
print('baseline', out['baseline'], flush=True)
target = os.path.join(tree, FILE)
for ident, new, expected, note in MUTANTS:
    open(target, 'w', encoding='utf8').write(text.replace(SLOT, new, 1))
    try:
        result = vitest()
    finally:
        run(['git', 'checkout', '--', FILE])
    outcome = 'errored' if result['selected'] == 0 else 'killed' if result['failed'] else 'survived'
    out['mutants'].append({'id': ident, 'file': FILE, 'old': SLOT, 'new': new, 'expected': expected, 'outcome': outcome, 'note': note, 'run': result})
    print(ident, outcome, [f['test'] for f in result['failed']], flush=True)
if not clean(): sys.exit('tree not restored')
out['totals'] = {
    'mutants': len(out['mutants']),
    'asExpected': sum(m['outcome'] == m['expected'] for m in out['mutants']),
    'killed': sum(m['outcome'] == 'killed' for m in out['mutants']),
    'restoreAmbiguousKilledByTimingTestAlone': [f['test'] for f in out['mutants'][0]['run']['failed']] == [TIMING],
}
with open(out_path, 'w', encoding='utf8') as f: f.write(json.dumps(out, indent=1) + '\n')
print('totals', out['totals'])
sys.exit(0 if out['totals']['asExpected'] == len(MUTANTS) and out['baseline']['failed'] == [] and out['baseline']['selected'] > 0 else 1)
