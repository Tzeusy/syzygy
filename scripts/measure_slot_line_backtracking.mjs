#!/usr/bin/env node
// Time the recorder template's line slot on a record it does not match (syzygy-bpyt.8.10). Evidence tool, not a check and not
// authority.
//
//   npx tsc -b packages/polaris-generation-consent
//   node scripts/measure_slot_line_backtracking.mjs --out <file.json>
//
// `SLOT.line` (packages/polaris-generation-consent/src/recorder-template.ts) is `[^\r\n]*\S[^\r\n]*`: a line holding n non-space
// characters matches it n ways, so a template whose literal text fails after several such slots retries every way of each. This script
// builds a template from the real provider statement version 2 record, the byte-exact record with the longest owner-selection slots,
// with its four selection values (`opening`, `label`, `description`, `quote`, the slots PROVIDER_V2_TEMPLATE has) as slots and every
// other byte literal, and times `templateFields` on the record and on altered copies (HEAD_FIELD_ALTERATION, PROSE_ALTERATIONS and the
// last line altered): once with `SLOT.line`, once with `[^\S\r\n]*\S[^\r\n]*`, which accepts the same lines (blanks other than CR and
// LF, then the first non-space character, then anything but CR and LF) in exactly one way. Timings depend on the machine; the match
// verdicts do not. It reads this checkout only and writes only `--out`.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT = fileURLToPath(import.meta.url);
const ROOT = path.resolve(path.dirname(SCRIPT), '..');
const RECORD = '.syzygy/governance/decisions/DOSSIER-AGENT-PROVIDER-V2-REDIS-ANTHROPIC-ACT.md';
const UNAMBIGUOUS = '[^\\S\\r\\n]*\\S[^\\r\\n]*';
const SLOTS = ['opening', 'label', 'description', 'quote'];
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const dist = rel => import(pathToFileURL(path.join(ROOT, rel)).href);

const out = process.argv.includes('--out') ? process.argv[process.argv.indexOf('--out') + 1] : undefined;
if (out === undefined) { process.stderr.write('usage: node scripts/measure_slot_line_backtracking.mjs --out <file.json>\n'); process.exit(2); }
const { recorderTemplate, templateFields, SLOT } = await dist('packages/polaris-generation-consent/dist/index.js');
const { HEAD_FIELD_ALTERATION, PROSE_ALTERATIONS } = await dist('packages/polaris-generation-consent/dist/testing.js');

const text = fs.readFileSync(path.join(ROOT, RECORD), 'utf8');
const values = {
  opening: /that opened "(.*)" by selecting the$/m.exec(text)?.[1],
  label: /^\| "(.*)" \| "(.*)" \|$/m.exec(text)?.[1],
  description: /^\| "(.*)" \| "(.*)" \|$/m.exec(text)?.[2],
  quote: /maps that option to its words "(.*?)"/.exec(text)?.[1],
};
if (SLOTS.some(slot => values[slot] === undefined)) throw new Error(`${RECORD}: an owner-selection line is not where the recorder writes it`);
// A `{word}` in the record would read as a slot: hide every brace that does not open one of the four, alike in template and texts.
const hide = s => s.replace(/\{(?!(?:opening|label|description|quote)\})/g, '\u0000');
let template = hide(text);
for (const slot of SLOTS) template = template.replace(`"${values[slot]}"`, `"{${slot}}"`);
const cases = [
  ['as recorded', text], ['date-field-altered', HEAD_FIELD_ALTERATION(text)], ...PROSE_ALTERATIONS.map(([name, alter]) => [name, alter(text)]),
  ['last line altered', text.replace(/\n([^\n]+)\n$/, '\n$1 [altered]\n')],
];
const runs = [];
for (const [pattern, source] of [['SLOT.line', SLOT.line], ['unambiguous', UNAMBIGUOUS]]) {
  const tpl = recorderTemplate(template, Object.fromEntries(SLOTS.map(slot => [slot, source])));
  for (const [name, body] of cases) {
    const started = performance.now(), fields = templateFields(tpl, hide(body));
    runs.push({ pattern, case: name, matched: fields !== null, ms: Math.round(performance.now() - started) });
    process.stderr.write(`${pattern} ${name}: ${runs.at(-1).ms} ms\n`);
  }
}
const git = (...args) => execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8' }).trim();
const document = {
  schema: 'consent-gate-slot-line-timing/1',
  bead: 'syzygy-bpyt.8.10',
  text: 'Evidence record, not authority: one byte-exact template read, timed with the line slot as it is and with an unambiguous pattern of the same language. Generated by the script named here; do not edit.',
  script: { path: 'scripts/measure_slot_line_backtracking.mjs', sha256: sha256(fs.readFileSync(SCRIPT)) },
  measuredOn: { commit: git('rev-parse', 'HEAD'), treeClean: git('status', '--porcelain', '--untracked-files=no') === '', node: process.version },
  record: { path: RECORD, sha256: sha256(text), slotLengths: Object.fromEntries(SLOTS.map(slot => [slot, values[slot].length])) },
  patterns: { 'SLOT.line': SLOT.line, unambiguous: UNAMBIGUOUS },
  timing: 'wall time of one templateFields call on the main thread, nothing else running in the process; depends on the machine',
  runs,
  verdictsAgree: cases.every(([name]) => runs.filter(r => r.case === name).every((r, _, all) => r.matched === all[0].matched)),
};
fs.writeFileSync(out, `${JSON.stringify(document, null, 1)}\n`);
process.exitCode = document.verdictsAgree ? 0 : 1;
