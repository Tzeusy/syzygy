"""syzygy-bpyt.8.32: the rule-6 record. In one committed, clean tree, run every control and mutant of mutants.json through
syzygy-bpyt.8.2's mutate.py (which applies the edits, runs the command and restores every file byte for byte), and write each result
beside its edits, its command, the commit and the subject's digests. A mutant is killed when its command exits nonzero; a control
must exit 0. Usage: run_record.py <tree> <mutants.json> <scratch-dir> <out.json>
"""
import hashlib, json, os, subprocess, sys

tree, mutants_file, scratch, out_file = sys.argv[1:5]
EVIDENCE = os.path.join(tree, 'docs/evidence/syzygy-bpyt-8-32')
MUTATE = os.path.join(tree, 'docs/evidence/syzygy-bpyt-8-2/mutate.py')
SUBJECT = ['packages/polaris-dossier/src/argv.ts', 'packages/polaris-dossier/src/argv.test.ts', 'packages/polaris-dossier/src/review.ts',
           'packages/polaris-dossier/src/state-directory.test.ts', 'packages/polaris-dossier/src/subpath-imports.test.ts',
           'packages/polaris-dossier/src/state-directory.ts', 'apps/syzygy/src/main.ts']
TOOLS = ['docs/evidence/syzygy-bpyt-8-2/mutate.py', 'docs/evidence/syzygy-bpyt-8-32/build_mutants.py',
         'docs/evidence/syzygy-bpyt-8-32/run_record.py', 'docs/evidence/syzygy-bpyt-8-32/row_status.py',
         'docs/evidence/syzygy-bpyt-8-32/as-root.mjs', 'docs/evidence/syzygy-bpyt-8-32/mutants.json']


def git(*args):
    return subprocess.run(['git', *args], cwd=tree, capture_output=True, check=True).stdout


def sha(path):
    return hashlib.sha256(open(os.path.join(tree, path), 'rb').read()).hexdigest()


assert git('status', '--porcelain') == b'', 'the tree must be committed and clean'
commit = git('rev-parse', 'HEAD').decode().strip()
base = git('merge-base', 'HEAD', 'origin/main').decode().strip()
specs = json.load(open(mutants_file))
os.makedirs(scratch, exist_ok=True)
env = {**os.environ, 'EVIDENCE': EVIDENCE, 'OUT': scratch}

r2 = json.load(open(os.path.join(tree, 'docs/evidence/syzygy-bpyt-8-2/mutants/R2-short-group-read-as-its-first-option.856d5c5c.json')))
r2_old = r2['edits'][0]['old']
results = []
for spec in specs['controls'] + specs['mutants']:
    spec_file = os.path.join(scratch, f"{spec['id']}.spec.json")
    json.dump(spec, open(spec_file, 'w'))
    run = subprocess.run(['python3', MUTATE, tree, spec_file, os.path.join(scratch, f"{spec['id']}.log")], cwd=tree, env=env,
                         capture_output=True, text=True, timeout=600)
    outcome = json.loads(run.stdout.strip().split('\n')[-1])
    control = spec['family'] == 'control'
    results.append({**spec, 'exit': outcome['exit'], 'failed': outcome['failed'], 'firstErrors': outcome['firstErrors'],
                    'verdict': ('passes' if outcome['exit'] == 0 else 'FAILS') if control else ('killed' if outcome['exit'] != 0 else 'SURVIVED')})
    print(spec['id'], results[-1]['verdict'], flush=True)
clean_after = git('status', '--porcelain') == b''

mutants = [r for r in results if r['family'] != 'control']
by_family = {}
for r in mutants:
    family = by_family.setdefault(r['family'], {'killed': 0, 'of': 0})
    family['of'] += 1
    family['killed'] += r['verdict'] == 'killed'
record = {
    'schema': 'argv-reader-table-mutants/1',
    'bead': 'syzygy-bpyt.8.32',
    'text': ('Evidence record, not authority: the rule-6 mutants of the tests this bead commits for the review of syzygy-bpyt.8.2 '
             '(docs/reviews/R-GP-IMPL-DOSSIER-CLI-TABLE-1-RAW.md, N1, N2, N5 and N8). Generated by run_record.py; do not edit.'),
    'subject': {'commit': commit, 'base': base, 'files': {path: sha(path) for path in SUBJECT},
                'diffSha256': hashlib.sha256(git('diff', base, commit, '--', 'apps', 'packages')).hexdigest(),
                'diffWhat': 'git diff <base> <commit> -- apps packages'},
    'tools': {path: sha(path) for path in TOOLS},
    'node': subprocess.run(['node', '--version'], capture_output=True, text=True).stdout.strip(),
    'killedWhen': 'the command exits nonzero; a control must exit 0',
    'notApplicable': [{'id': r2['id'], 'from': 'docs/evidence/syzygy-bpyt-8-2/mutants/R2-short-group-read-as-its-first-option.856d5c5c.json',
                       'why': 'written against 856d5c5c; its old fragment occurs in argv.ts at this commit this many times',
                       'occurrences': open(os.path.join(tree, 'packages/polaris-dossier/src/argv.ts')).read().count(r2_old),
                       'replacedBy': 'R2b-group-read-by-its-first-option'}],
    'summary': {'controls': {r['id']: r['verdict'] for r in results if r['family'] == 'control'}, 'families': by_family,
                'killed': sum(r['verdict'] == 'killed' for r in mutants), 'of': len(mutants), 'restoredClean': clean_after},
    'results': results,
}
json.dump(record, open(out_file, 'w'), indent=1, ensure_ascii=False)
open(out_file, 'a').write('\n')
print(json.dumps(record['summary']))
