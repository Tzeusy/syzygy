"""syzygy-bpyt.8.32: re-run syzygy-bpyt.8.2's three argv goldens (docs/evidence/syzygy-bpyt-8-2/) in one committed, clean, built
tree, and compare each output's sha256 with the digest 8.2 recorded at its base (evidence.json `goldens.<kind>.base`). An equal digest
means no row differs. The goldens name /tmp/la-b82/{g,gcwd,home,rtf} in their messages, so those paths are fixed; the first three
must be absent or empty. The subprocess golden takes the parse golden's output as its input, which stands for 8.2's base parse
output only when the two digests are equal (recorded). Usage: rerun_goldens.py <tree> <scratch-dir> <out.json>
"""
import hashlib, json, os, shutil, subprocess, sys

tree, scratch, out_file = sys.argv[1:4]
G82 = os.path.join(tree, 'docs/evidence/syzygy-bpyt-8-2')
recorded = json.load(open(os.path.join(G82, 'evidence.json')))['goldens']


def git(*args):
    return subprocess.run(['git', *args], cwd=tree, capture_output=True, check=True).stdout


def digest(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


def run(command, **extra):
    done = subprocess.run(command, shell=True, cwd=tree, capture_output=True, text=True, env={**os.environ, **extra}, timeout=3600)
    return {'command': command, 'exit': done.returncode, 'tail': (done.stdout + done.stderr).strip().split('\n')[-3:]}


assert git('status', '--porcelain') == b'', 'the tree must be committed and clean'
commit = git('rev-parse', 'HEAD').decode().strip()
for d in ('/tmp/la-b82/g', '/tmp/la-b82/gcwd', '/tmp/la-b82/home'):
    os.makedirs(d, exist_ok=True)
    assert os.listdir(d) == [], f'{d} is not empty'
os.makedirs(scratch, exist_ok=True)
steps = {}
steps['build'] = run('npm run build')
harness = os.path.join(tree, 'packages/polaris-dossier/src/zz-golden.test.ts')
shutil.copyfile(os.path.join(G82, 'dossier-golden-harness.ts'), harness)
try:
    steps['dossier'] = run('npx vitest run --project @syzygy/polaris-dossier packages/polaris-dossier/src/zz-golden.test.ts',
                           GOLDEN_CORPUS=os.path.join(G82, 'dossier-corpus.json'), GOLDEN_OUT=os.path.join(scratch, 'dossier.json'),
                           GOLDEN_CWD='/tmp/la-b82/gcwd', TMPDIR='/tmp/la-b82/g', CI='1')
finally:
    os.remove(harness)
steps['extract'] = run(f"python3 {G82}/extract_parsers.py {tree} {scratch}/oracle")
steps['parse'] = run(f"node {G82}/parse-golden.mjs {scratch}/oracle {G82} {scratch}/parse.json")
steps['subprocess'] = run(f"python3 {G82}/subprocess_golden.py {tree} {scratch}/parse.json {scratch}/subprocess.json")

goldens = {}
for kind in ('dossier', 'parse', 'subprocess'):
    produced = os.path.join(scratch, f'{kind}.json')
    rows = json.load(open(produced)) if os.path.isfile(produced) else None
    count = None if rows is None else (len(rows) if isinstance(rows, list) else sum(len(v) for v in rows.values()))
    sha = digest(produced) if rows is not None else None
    goldens[kind] = {'what': recorded[kind]['what'], 'rows': count, 'sha256': sha, 'baseSha256': recorded[kind]['base'],
                     'equalToBase': sha == recorded[kind]['base']}
record = {
    'schema': 'argv-golden-rerun/1',
    'bead': 'syzygy-bpyt.8.32',
    'text': ('Evidence record, not authority: syzygy-bpyt.8.2\'s argv goldens re-run at this bead\'s commit, compared by digest with '
             'the outputs 8.2 recorded at its base. Generated by rerun_goldens.py; do not edit.'),
    'commit': commit,
    'files': {path: digest(os.path.join(tree, path)) for path in ('packages/polaris-dossier/src/argv.ts', 'packages/polaris-dossier/src/cli.ts',
                                                                 'packages/polaris-dossier/src/polaris.ts', 'apps/syzygy/src/main.ts')},
    'tools': {os.path.relpath(p, tree): digest(p) for p in [os.path.join(G82, n) for n in ('dossier-golden-harness.ts', 'extract_parsers.py',
              'parse-golden.mjs', 'subprocess_golden.py', 'dossier-corpus.json', 'daemon-corpus.json', 'polaris-corpus.json')]
              + [os.path.join(tree, 'docs/evidence/syzygy-bpyt-8-32/rerun_goldens.py')]},
    'node': subprocess.run(['node', '--version'], capture_output=True, text=True).stdout.strip(),
    'steps': steps,
    'goldens': goldens,
    'cleanAfter': git('status', '--porcelain') == b'',
}
json.dump(record, open(out_file, 'w'), indent=1)
open(out_file, 'a').write('\n')
print(json.dumps({k: {'rows': v['rows'], 'equalToBase': v['equalToBase']} for k, v in goldens.items()}), record['cleanAfter'])
