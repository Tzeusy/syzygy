"""syzygy-bpyt.8.32 (N4): is ReviewPacketResult at this commit the same type as before Outcome? Lift the alias, as text, from three
commits: <before> (the base of syzygy-bpyt.8.2, two ok: true variants), <was> (8.2 merged, one Outcome with a union report) and the
tree. Check every direction of assignability with `tsc --strict` and no ambient types, each in its own file, and compare what each review.ts emits through
TypeScript's transpileModule (types only must emit nothing). ReverifyRefusal is a placeholder shared by all three, so it cannot make
them differ. Usage: probe_review_type.py <tree> <before-commit> <was-commit> <scratch-dir> <out.json>
"""
import hashlib, json, os, subprocess, sys

tree, before, was, scratch, out_file = sys.argv[1:6]
REVIEW = 'packages/polaris-dossier/src/review.ts'
END = '\n\n/** `syzygy dossier review-packet <run>'


def git(*args):
    return subprocess.run(['git', *args], cwd=tree, capture_output=True, check=True).stdout.decode()


def region(text, start):
    assert text.count(start) == 1 and text.count(END) == 1, start
    a = text.index(start)
    return text[a:text.index(END, a)]


texts = {'before': git('show', f'{before}:{REVIEW}'), 'was': git('show', f'{was}:{REVIEW}'), 'head': open(os.path.join(tree, REVIEW)).read()}
aliases = {
    'Before': region(texts['before'], 'export type ReviewPacketResult =').replace('export type ReviewPacketResult', 'type Before'),
    'Was': region(texts['was'], 'export type ReviewPacketResult =').replace('export type ReviewPacketResult', 'type Was'),
    'Head': region(texts['head'], 'type ReviewPacketRefusal =').replace('export type ReviewPacketResult', 'type Head')
            .replace('ReviewPacketRefusal', 'HeadRefusal'),
}
outcome = open(os.path.join(tree, 'packages/polaris-dossier/src/outcome.ts')).read().replace('export type Outcome', 'type Outcome')
prelude = 'type ReverifyRefusal = { readonly placeholder: true };\n' + outcome + '\n' + '\n'.join(aliases.values()) + '\n'
os.makedirs(scratch, exist_ok=True)
tsc = os.path.join(tree, 'node_modules/.bin/tsc')
checks = []
for source, target in [('Before', 'Head'), ('Head', 'Before'), ('Before', 'Was'), ('Was', 'Before'), ('Was', 'Head'), ('Head', 'Was')]:
    probe = os.path.join(scratch, f'{source}-to-{target}.ts')
    open(probe, 'w').write(prelude + f'export const assign = (value: {source}): {target} => value;\n')
    config = os.path.join(scratch, f'{source}-to-{target}.json')
    json.dump({'compilerOptions': {'strict': True, 'noEmit': True, 'target': 'es2022', 'module': 'nodenext', 'types': []}, 'files': [probe]}, open(config, 'w'))
    done = subprocess.run([tsc, '-p', config], capture_output=True, text=True)
    errors = [line.split(': ', 1)[1] for line in done.stdout.split('\n') if ': error TS' in line]
    checks.append({'assign': f'{source} to {target}', 'exit': done.returncode, 'errors': errors})

emit_script = ("const ts = require('typescript'); const fs = require('fs');"
               "const out = {}; for (const f of process.argv.slice(1)) out[f] = require('crypto').createHash('sha256')"
               ".update(ts.transpileModule(fs.readFileSync(f, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022,"
               " module: ts.ModuleKind.NodeNext, verbatimModuleSyntax: false } }).outputText).digest('hex');"
               "console.log(JSON.stringify(out));")
paths = {}
for name, text in texts.items():
    paths[name] = os.path.join(scratch, f'review-{name}.ts')
    open(paths[name], 'w').write(text)
emitted = json.loads(subprocess.run(['node', '-e', emit_script, *paths.values()], cwd=tree, capture_output=True, text=True, check=True).stdout)
record = {
    'schema': 'review-packet-result-type/1',
    'bead': 'syzygy-bpyt.8.32',
    'text': 'Evidence record, not authority: the N4 probe of ReviewPacketResult. Generated by probe_review_type.py; do not edit.',
    'commits': {'before': git('rev-parse', before).strip(), 'was': git('rev-parse', was).strip(), 'head': git('rev-parse', 'HEAD').strip()},
    'reviewTsSha256': {name: hashlib.sha256(text.encode()).hexdigest() for name, text in texts.items()},
    'tsc': subprocess.run([tsc, '--version'], capture_output=True, text=True).stdout.strip(),
    'probeSha256': hashlib.sha256(prelude.encode()).hexdigest(),
    'assignability': checks,
    'transpiledJsSha256': {name: emitted[paths[name]] for name in texts},
    'tool': hashlib.sha256(open(os.path.abspath(__file__), 'rb').read()).hexdigest(),
}
json.dump(record, open(out_file, 'w'), indent=1)
open(out_file, 'a').write('\n')
print(json.dumps({'assignability': [(c['assign'], c['exit']) for c in checks], 'js': record['transpiledJsSha256']}))
