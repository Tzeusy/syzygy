"""syzygy-bpyt.8.34: the 8.2 review's 1,696-row dossier golden at this commit. In one committed, clean tree, build the dossier package
and run that review's dossier_run.mjs over its corpus from an empty directory, then compare the output's sha256 with the digest the
review of 8.32 recorded at its base and head (R-GP-IMPL-ARGV-TABLE-1-RAW.md, section 3, "Goldens"). An equal digest means no row
differs. Usage: dossier_golden.py <tree> <scratch dir> <out.json>   (the scratch directory must not exist)
"""
import hashlib, json, os, subprocess, sys

tree, scratch, out_file = sys.argv[1:4]
TOOLS = 'docs/evidence/dossier-cli-table-review-2026-10-24'
RECORDED = '54983601a3d783ee442719858e6e1d5fecad9f6589c170d71969b7a4e1a4762b'


def git(*args):
    return subprocess.run(['git', *args], cwd=tree, capture_output=True, check=True).stdout


def sha(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


assert git('status', '--porcelain') == b'', 'the tree must be committed and clean'
commit = git('rev-parse', 'HEAD').decode().strip()
os.makedirs(os.path.join(scratch, 'cwd'))
os.makedirs(os.path.join(scratch, 'tmp'))
build = subprocess.run(['npx', 'tsc', '-b', '--force', 'packages/polaris-dossier'], cwd=tree, capture_output=True, text=True, timeout=1200)
output = os.path.join(scratch, 'dossier.jsonl')
run = subprocess.run(['node', os.path.join(tree, TOOLS, 'tools/dossier_run.mjs'), tree, os.path.join(tree, TOOLS, 'corpus/dossier.json'), output],
                     cwd=os.path.join(scratch, 'cwd'), capture_output=True, text=True, env={**os.environ, 'TMPDIR': os.path.join(scratch, 'tmp')},
                     timeout=1200)
record = {
    'bead': 'syzygy-bpyt.8.34', 'commit': commit,
    'text': ('Evidence record, not authority: the 8.2 review\'s dossier golden run at this commit. Generated by dossier_golden.py; '
             'do not edit.'),
    'tool': {'path': f'{TOOLS}/tools/dossier_run.mjs', 'sha256': sha(os.path.join(tree, TOOLS, 'tools/dossier_run.mjs'))},
    'corpus': {'path': f'{TOOLS}/corpus/dossier.json', 'sha256': sha(os.path.join(tree, TOOLS, 'corpus/dossier.json'))},
    'harnessSha256': sha(__file__),
    'buildExit': build.returncode, 'runExit': run.returncode, 'runOutput': run.stdout.strip(),
    'outputSha256': sha(output), 'recordedSha256': RECORDED,
    'recordedWhere': 'docs/reviews/R-GP-IMPL-ARGV-TABLE-1-RAW.md, section 3 "Goldens": 8.2\'s base output, and the head of 8.32',
    'equal': sha(output) == RECORDED,
    'cwdEmptyAfter': os.listdir(os.path.join(scratch, 'cwd')) == [],
    'trackedTreeCleanAfter': git('status', '--porcelain') == b'',
}
json.dump(record, open(out_file, 'w'), indent=1)
open(out_file, 'a').write('\n')
print(json.dumps({k: record[k] for k in ('buildExit', 'runExit', 'runOutput', 'outputSha256', 'equal', 'cwdEmptyAfter', 'trackedTreeCleanAfter')}))
