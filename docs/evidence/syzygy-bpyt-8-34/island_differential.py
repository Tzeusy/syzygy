"""syzygy-bpyt.8.34: the island guard's reach before and after it moved to workspace-reach.testkit.ts. In one committed, clean tree,
write island-boundary.test.ts's module text before its first `describe(` twice, as two scratch modules beside it: once from <base>,
once from the tree, each exporting its `reach`. A scratch test then runs both on the CLI entry and on the consent package root (the
entries the guard asks about) and writes their answers. Equal answers mean the guard sees what it saw. The scratch files are deleted
and the tree must be clean after. Usage: island_differential.py <tree> <base> <out.json>   (TMPDIR names the scratch area)
"""
import hashlib, json, os, subprocess, sys

tree, base, out_file = sys.argv[1:4]
GUARD = 'packages/polaris-generation-core/src/island-boundary.test.ts'
TESTKIT = 'packages/polaris-generation-core/src/workspace-reach.testkit.ts'
DIR = os.path.join(tree, 'packages/polaris-generation-core/src')
ENTRIES = ['apps/syzygy/src/main.ts', 'packages/polaris-generation-consent/src/index.ts']
answers = os.path.join(os.environ.get('TMPDIR', '/tmp'), 'island-differential-answers.json')


def git(*args):
    return subprocess.run(['git', *args], cwd=tree, capture_output=True, check=True).stdout


def head_of(text):
    return text[:text.index("describe('the syzygy CLI and the parked provider island'")] + 'export { reach };\n'


assert git('status', '--porcelain') == b'', 'the tree must be committed and clean'
commit = git('rev-parse', 'HEAD').decode().strip()
base = git('rev-parse', base).decode().strip()
texts = {'base': git('show', f'{base}:{GUARD}').decode(), 'head': open(os.path.join(tree, GUARD)).read()}
scratch = {side: os.path.join(DIR, f'zz-island-{side}.ts') for side in texts}
test = os.path.join(DIR, 'zz-island-differential.test.ts')
try:
    for side, text in texts.items():
        open(scratch[side], 'w').write(head_of(text))
    open(test, 'w').write(f"""import {{ writeFileSync }} from 'node:fs';
import {{ it }} from 'vitest';
import {{ reach as baseReach }} from './zz-island-base.js';
import {{ reach as headReach }} from './zz-island-head.js';

it('answers', () => {{
  const entries = {json.dumps(ENTRIES)};
  writeFileSync({json.dumps(answers)}, JSON.stringify(entries.map((entry) => ({{ entry, base: baseReach(entry), head: headReach(entry) }}))));
}});
""")
    run = subprocess.run(['npx', 'vitest', 'run', '--project', '@syzygy/polaris-generation-core', 'packages/polaris-generation-core/src/zz-island-differential.test.ts'],
                         cwd=tree, capture_output=True, text=True, env={**os.environ, 'CI': '1'}, timeout=600)
finally:
    for path in [*scratch.values(), test]:
        if os.path.exists(path):
            os.remove(path)
results = json.load(open(answers))
record = {
    'bead': 'syzygy-bpyt.8.34',
    'text': ('Evidence record, not authority: island-boundary.test.ts\'s reach at the base and at the commit, which moved its walk to '
             'workspace-reach.testkit.ts, run on the entries the guard asks about. Generated by island_differential.py; do not edit.'),
    'commit': commit, 'base': base,
    'files': {'guardAtBase': hashlib.sha256(texts['base'].encode()).hexdigest(), 'guardAtCommit': hashlib.sha256(texts['head'].encode()).hexdigest(),
              'testkitAtCommit': hashlib.sha256(open(os.path.join(tree, TESTKIT), 'rb').read()).hexdigest()},
    'toolSha256': hashlib.sha256(open(__file__, 'rb').read()).hexdigest(),
    'vitestExit': run.returncode,
    'entries': [{'entry': r['entry'], 'equal': json.dumps(r['base'], sort_keys=True) == json.dumps(r['head'], sort_keys=True),
                 'reachable': len(r['head']['reachable']), 'intoIsland': len(r['head']['intoIsland']), 'unresolved': len(r['head']['unresolved']),
                 'answerSha256': {side: hashlib.sha256(json.dumps(r[side], sort_keys=True).encode()).hexdigest() for side in ('base', 'head')}}
                for r in results],
    'trackedTreeCleanAfter': git('status', '--porcelain') == b'',
}
json.dump(record, open(out_file, 'w'), indent=1)
open(out_file, 'a').write('\n')
print(json.dumps({k: record[k] for k in ('vitestExit', 'entries', 'trackedTreeCleanAfter')}))
