"""syzygy-bpyt.8.34: the rule-6 record. In one committed, clean tree, apply each control and mutant of mutants.json (each `old` must
occur exactly once in its file and is replaced by `new`; a `create` writes a file that must not exist), run its command, restore every
file byte for byte and delete every created file, and write each result beside its edits, its command, the commit and the subject's
digests. A mutant is killed when its command exits nonzero; a control must exit 0. Usage: run_record.py <tree> <mutants.json> <scratch
dir> <out.json>
"""
import hashlib, json, os, re, subprocess, sys

tree, mutants_file, scratch, out_file = sys.argv[1:5]
SUBJECT = ['packages/polaris-dossier/src/argv.test.ts', 'packages/polaris-dossier/src/subpath-imports.test.ts',
           'packages/polaris-generation-core/src/island-boundary.test.ts', 'packages/polaris-generation-core/src/workspace-reach.testkit.ts',
           'packages/polaris-dossier/src/argv.ts', 'packages/polaris-dossier/src/cli.ts', 'packages/polaris-dossier/src/polaris.ts',
           'apps/syzygy/src/main.ts']
TOOLS = ['docs/evidence/syzygy-bpyt-8-34/build_mutants.py', 'docs/evidence/syzygy-bpyt-8-34/run_record.py',
         'docs/evidence/syzygy-bpyt-8-34/mutants.json']


def git(*args):
    return subprocess.run(['git', *args], cwd=tree, capture_output=True, check=True).stdout


def sha(path):
    return hashlib.sha256(open(os.path.join(tree, path), 'rb').read()).hexdigest()


assert git('status', '--porcelain') == b'', 'the tree must be committed and clean'
commit = git('rev-parse', 'HEAD').decode().strip()
base = git('merge-base', 'HEAD', 'origin/main').decode().strip()
specs = json.load(open(mutants_file))
os.makedirs(scratch, exist_ok=True)
results = []
for spec in specs['controls'] + specs['mutants']:
    originals, created = {}, []
    try:
        for edit in spec['edits']:
            path = os.path.join(tree, edit['file'])
            if 'create' in edit:
                assert not os.path.exists(path), (spec['id'], edit['file'])
                open(path, 'w').write(edit['create'])
                created.append(path)
                continue
            originals.setdefault(path, open(path, 'rb').read())
            text = open(path).read()
            assert text.count(edit['old']) == 1, (spec['id'], edit['file'], text.count(edit['old']))
            open(path, 'w').write(text.replace(edit['old'], edit['new']))
        run = subprocess.run(spec['command'], shell=True, cwd=tree, capture_output=True, text=True, timeout=900)
    finally:
        for path, data in originals.items():
            open(path, 'wb').write(data)
        for path in created:
            os.remove(path)
    plain = re.sub(r'\x1b\[[0-9;]*m', '', run.stdout + run.stderr)
    open(os.path.join(scratch, f"{spec['id']}.log"), 'w').write(plain)
    tests = [line.strip() for line in plain.split('\n') if re.match(r'\s*Tests\s', line)]
    failed = [line.strip() for line in plain.split('\n') if re.match(r'\s*FAIL\s', line)]
    errors = [line.strip() for line in plain.split('\n') if re.match(r'\s*(AssertionError|Error|TypeError|SyntaxError):', line)]
    control = spec['family'] == 'control'
    verdict = ('passes' if run.returncode == 0 else 'FAILS') if control else ('killed' if run.returncode != 0 else 'survives')
    results.append({**spec, 'exit': run.returncode, 'tests': tests, 'failed': failed[:20], 'firstErrors': errors[:5], 'verdict': verdict,
                    'asExpected': verdict == spec['expect']})
    print(spec['id'], verdict, tests, flush=True)
clean_after = git('status', '--porcelain') == b''

mutants = [r for r in results if r['family'] != 'control']
by_family = {}
for r in mutants:
    family = by_family.setdefault(r['family'], {'killed': 0, 'of': 0})
    family['of'] += 1
    family['killed'] += r['verdict'] == 'killed'
record = {
    'schema': 'argv-table-follow-up-mutants/1',
    'bead': 'syzygy-bpyt.8.34',
    'text': ('Evidence record, not authority: the rule-6 mutants of the tests this bead commits for the review of syzygy-bpyt.8.32 '
             '(docs/reviews/R-GP-IMPL-ARGV-TABLE-1-RAW.md, N1-N6). Generated by run_record.py; do not edit.'),
    'subject': {'commit': commit, 'base': base, 'files': {path: sha(path) for path in SUBJECT},
                'diffSha256': hashlib.sha256(git('diff', base, commit, '--', 'apps', 'packages')).hexdigest(),
                'diffWhat': 'git diff <base> <commit> -- apps packages'},
    'tools': {path: sha(path) for path in TOOLS},
    'node': subprocess.run(['node', '--version'], capture_output=True, text=True).stdout.strip(),
    'killedWhen': 'the command exits nonzero; a control must exit 0',
    'summary': {'controls': {r['id']: r['verdict'] for r in results if r['family'] == 'control'}, 'families': by_family,
                'killed': sum(r['verdict'] == 'killed' for r in mutants), 'of': len(mutants),
                'notAsExpected': [r['id'] for r in results if not r['asExpected']], 'restoredClean': clean_after},
    'results': results,
}
json.dump(record, open(out_file, 'w'), indent=1, ensure_ascii=False)
open(out_file, 'a').write('\n')
print(json.dumps(record['summary']))
